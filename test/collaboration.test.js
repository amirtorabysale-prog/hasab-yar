import test from 'node:test';
import assert from 'node:assert/strict';
import {
  audioDurationMs, estimateProviderCostMicrousd, monthlyPackageChecklist, pilotRetentionSummary,
  usageQuotaSnapshot,
} from '../server/collaboration.js';
import { encodePcm16Wav } from '../src/lib/wavRecorder.js';

test('paid-service quotas never imply that core manual entry is blocked', () => {
  const quotas = usageQuotaSnapshot('free', { smartVoiceRequests: 30, receiptOcrPages: 10, members: 2 });
  const voice = quotas.find((item) => item.id === 'smartVoiceRequests');
  const ocr = quotas.find((item) => item.id === 'receiptOcrPages');
  assert.equal(voice.exhausted, true);
  assert.match(voice.note, /Chrome.*دستی/);
  assert.equal(ocr.exhausted, true);
  assert.match(ocr.note, /دستی/);
});

test('provider costs stay unknown until an explicit rate is configured', () => {
  assert.equal(estimateProviderCostMicrousd({ capability: 'server_voice', provider: 'openai', durationMs: 60_000 }, {}), null);
  assert.equal(estimateProviderCostMicrousd({ capability: 'server_voice', provider: 'openai', durationMs: 30_000 }, { OPENAI_TRANSCRIBE_USD_PER_MINUTE: '0.02' }), 10_000);
  assert.equal(estimateProviderCostMicrousd({ capability: 'receipt_ocr', provider: 'openai' }, { OPENAI_OCR_USD_PER_IMAGE: '0.005' }), 5_000);
});

test('reads the duration of the PCM WAV generated by the browser', () => {
  const wav = Buffer.from(encodePcm16Wav(new Float32Array(16_000), 16_000));
  assert.equal(audioDurationMs(wav, 'audio/wav'), 1_000);
  assert.equal(audioDurationMs(Buffer.from('not-wav'), 'audio/webm'), 0);
});

test('monthly readiness reports every unresolved accounting exception', () => {
  const checklist = monthlyPackageChecklist({
    incompleteReceipts: [{ id: 'r1' }],
    closingDiscrepancies: [],
    reconciliationIssues: [{ id: 'b1' }],
    openRequests: [{ id: 'q1', status: 'open' }, { id: 'q2', status: 'answered' }],
  });
  assert.equal(checklist.ready, false);
  assert.equal(checklist.checks.find((item) => item.id === 'requests').count, 1);
});

test('pilot retention excludes workspaces that have not reached week four', () => {
  const summary = pilotRetentionSummary([
    { eligibleForWeekFour: true, weekFourActive: true, willingnessToPay: 'yes' },
    { eligibleForWeekFour: true, weekFourActive: false, willingnessToPay: 'no' },
    { eligibleForWeekFour: false, weekFourActive: true, willingnessToPay: 'maybe' },
  ]);
  assert.equal(summary.retentionPercent, 50);
  assert.equal(summary.willingnessPercent, 33);
});
