import test from 'node:test';
import assert from 'node:assert/strict';
import { parseFinancialText } from '../shared/parser.js';
import { classifyCategory } from '../shared/categoryRules.js';
import { readUnpaidSignal } from '../shared/accrualSpeech.js';
import { runVoice } from './helpers/voicePipeline.js';

/**
 * دو نقصِ مسیر بی‌AI از دور ۲۰ سناریوی سخت (۲۹ مهر ۱۴۰۵؛ docs/testing/hard-twenty-2026-10-18.md).
 *
 * T01 — «سوخت» با `includes` در «سوختهٔ»، «سوختگی» و فعلِ «لامپ سوخت» هم پیدا می‌شد و
 * قطعهٔ سوخته‌ای که عوض شده بود «سوخت و ایاب‌وذهاب» ثبت می‌شد. خانواده: صفتِ سوخته،
 * سوختگی، فعلِ سوختن پس از نامِ وسیله، و عوض/تعمیرِ همان قطعه؛ منفی: سوختِ واقعی.
 *
 * T18 — «قراره تا آبان پرداختش کنیم» نشانهٔ پرداخت‌نشدن را نمی‌ساخت، چون الگو فقط
 * «قراره پرداخت»ِ چسبیده را می‌شناخت. نتیجه: خروج نقدی برای پولی که نرفته (قاعدهٔ ۴).
 * خانواده: قراره/قرار است/باید با واژه‌های میانی، ضمیرِ مفعولی («پرداختش»)، آینده
 * («می‌دیم»، «پرداخت می‌کنیم»)، اعداد لاتین؛ منفی: «قرار بود … ولی امروز دادیم»،
 * پرداختِ انجام‌شده، و وعدهٔ سوم‌شخص (مسیر طلب).
 */

const FUEL = 'سوخت و ایاب‌وذهاب';
const REPAIR = 'تعمیر و نگهداری';
const T01 = 'یه کلید برق ۴۵۰ هزار تومانی برای تابلوی برق دفتر خریدیم که کلید سوختهٔ قبلی رو عوض کردیم؛ نقد از صندوق.';
const T18 = 'قبض برق مهر مغازه ۴ میلیون تومان اومده ولی قراره تا آبان پرداختش کنیم.';
const category = (text) => parseFinancialText(text).transactions[0]?.category;

test('T01 و خانواده‌اش: قطعهٔ سوخته که عوض یا تعمیر شد، تعمیر و نگهداری است، نه سوخت', () => {
  for (const text of [
    T01,
    'لامپ سوخته رو عوض کردیم ۸۰ هزار تومن',
    'فیوز تابلو سوخت، یه فیوز نو ۵۰ هزار تومن خریدیم و عوضش کردیم',
    'موتور کولر سوخت و ۳ میلیون دادیم تعمیرش کنن',
    'سیم‌کشی سوختهٔ انبار رو ۲ میلیون درست کردیم',
    'سوختگی برد دستگاه رو ۱ میلیون تعمیر کردیم',
    'کلید سوخته رو عوض کردیم 120 هزار تومن',
  ]) {
    assert.equal(category(text), REPAIR, text);
  }
});

test('«سوخته» و فعلِ «سوخت» به‌تنهایی سوخت نیستند', () => {
  for (const text of ['کلید سوخته', 'لامپ سوخت', 'سوختگی کابل', 'کلید برق سوخت']) {
    assert.notEqual(classifyCategory(text, 'expense').category, FUEL, text);
  }
});

test('سوختِ واقعی همان سوخت می‌ماند', () => {
  for (const text of [
    'سوخت ماشین ۵۰۰ هزار تومن دادیم',
    '۳۰۰ هزار تومن سوخت زدیم',
    'هزینهٔ سوخت ژنراتور ۲ میلیون پرداخت کردیم',
    'سوخت‌گیری ون شرکت ۴۰۰ هزار تومن دادیم',
    'بنزین ۲۰۰ هزار زدم',
    '۵۰۰ هزار تومن دادیم بابت سوخت',
  ]) {
    assert.equal(category(text), FUEL, text);
  }
});

test('«عوض کردیم» بی قطعهٔ سوخته یا خراب، تعمیر نمی‌سازد', () => {
  assert.notEqual(category('قرارداد رو عوض کردیم و ۲ میلیون پیش‌پرداخت دادیم'), REPAIR);
  assert.notEqual(category('۱۰ میلیون دلار عوض کردیم'), REPAIR);
});

const noCashPosting = (result) => result.items.every((item) => !(item.outcome === 'post' && /^cash-/.test(item.kind || '')));

test('T18 و خانواده‌اش: پولی که قرار است بعداً بدهیم، ردیف نقدی نمی‌سازد', () => {
  for (const text of [
    T18,
    'قبض گاز ۲ میلیون اومده، قرار است آخر ماه بپردازیم',
    'اجارهٔ مهر انبار ۸ میلیون اومده، قراره هفته بعد بدیم',
    'فاکتور تعمیرکار ۳ میلیون رسیده، ماه بعد پرداخت می‌کنیم',
    'قبض آب ۵۰۰ هزار تومن اومده هنوز پرداختش نکردیم',
    'حقوق مهر پرسنل ۴۰ میلیون رو باید تا پنجم آبان بدیم',
    'قبض تلفن ۹۰۰ هزار تومن اومده میدیم هفته دیگه',
    'قبض برق ۴ میلیون اومده، تا آبان پرداختش می‌کنیم',
    'قبض برق 4 میلیون اومده قراره آبان پرداختش کنیم',
  ]) {
    assert.equal(readUnpaidSignal(text), true, `نشانهٔ پرداخت‌نشدن: ${text}`);
    assert.equal(parseFinancialText(text).transactions[0]?.unpaidSignal, true, `روی ردیف پارسر: ${text}`);
    const result = runVoice(text);
    assert.ok(noCashPosting(result), `ردیف نقدی نباید ساخته شود: ${text} → ${JSON.stringify(result.items.map((item) => [item.outcome, item.kind]))}`);
  }
  assert.equal(runVoice(T18).items[0].kind, 'payable-opened', 'تعهدِ پرداخت باز می‌شود');
});

test('پرداختِ انجام‌شده و وعدهٔ سوم‌شخص همان رفتار قبلی را دارند', () => {
  for (const text of [
    'قبض برق ۴ میلیون رو قرار بود آبان بدیم ولی امروز پرداخت کردیم',
    'قبض برق ۴ میلیون پرداخت کردیم',
    'اجاره رو قراره بدیم، ولی همین الان ۸ میلیون دادیم',
    'هر ماه ۵ میلیون اجاره می‌دیم، این ماه هم دادیم',
  ]) {
    assert.equal(readUnpaidSignal(text), false, text);
    assert.equal(runVoice(text).items[0]?.kind, 'cash-expense', text);
  }
  // پولِ آینده برای خدمتِ آینده هنوز بدهی نیست؛ موتور دورهٔ خدمت را می‌پرسد (engine5-p2).
  assert.equal(readUnpaidSignal('اجاره دفتر رو ماه بعد ۱۰ میلیون میدیم'), false);
  // «تحویلش میدیم» دادنِ کالاست، نه پول — حتی کنار فاکتور.
  assert.equal(readUnpaidSignal('فاکتور فروش صادر شد، جنس رو سه ماه بعد تحویلش میدیم'), false);
  assert.equal(readUnpaidSignal('آقای رضایی ۳۰ میلیون بیعانه داد برای پارچه که سه ماه بعد تحویلش میدیم'), false);
  // وعدهٔ مشتری یا مستاجر مسیر طلب است: هیچ ثبتی تا پول نرسیده.
  assert.equal(readUnpaidSignal('مستاجر قراره ۱۰ میلیون اجاره رو هفته بعد بده'), false);
  assert.deepEqual(runVoice('مستاجر قراره ۱۰ میلیون اجاره رو هفته بعد بده').items, []);
});
