import { normalizePersian } from './normalize.js';

/**
 * اثر انگشت محتوای یک رویداد — برای تشخیص تکرار میان کانال‌ها.
 *
 * چرا لازم است:
 *
 * `source_event_id` یکتاست و کار می‌کند، ولی تک‌کاناله است. همان فاکتور اگر یک
 * بار با صدا گفته شود و یک بار عکس رسیدش فرستاده شود، دو شناسهٔ منبع متفاوت
 * دارد و دو سند می‌سازد. کاربر هم هیچ‌وقت نمی‌فهمد، چون هر دو ثبت از دید خودش
 * درست بوده‌اند و هیچ خطایی هم ندیده.
 *
 * چه چیزی در اثر انگشت می‌آید و چه چیزی نه:
 *
 * - **می‌آید:** نوع رویداد، مبلغ، روزِ وقوع، دسته، طرف حساب، حساب نقدی. این‌ها
 *   همان چیزهایی‌اند که دو ثبت را «یک رویداد» می‌کنند.
 * - **نمی‌آید:** کانال ورود، متن خام، ساعت. کاربر صبح ضبط می‌کند و ظهر عکس
 *   رسید را می‌فرستد؛ اگر ساعت در اثر انگشت بیاید هیچ تکراری هیچ‌وقت پیدا
 *   نمی‌شود. و متن خام از دو کانال هیچ‌وقت یکی نیست.
 *
 * روز، نه لحظه: مرز روز از همان تاریخ ISO گرفته می‌شود و منطقهٔ زمانی دخالت
 * ندارد، چون هر دو ثبت از یک دستگاه و یک تنظیم می‌آیند.
 */

/** نام‌های فارسی با نیم‌فاصله و «ی» عربی، دو شکل یک چیزند. */
const key = (value) => normalizePersian(String(value ?? '')).replace(/\s+/g, ' ').trim().toLowerCase();

export function eventFingerprint(event = {}) {
  if (!event.kind || !(event.amount > 0) || !event.occurredAt) return null;
  return [
    event.kind,
    event.amount,
    String(event.occurredAt).slice(0, 10),
    key(event.category),
    key(event.counterparty),
    key(event.accountId),
  ].join('|');
}
