const LEGACY_CHART_CODES = Object.freeze({ 'inc-rent': '6201', 'exp-insurance': '8109', 'exp-tax': '8109', 'exp-fuel': '8103', 'exp-office': '8109', 'exp-marketing': '8109', 'exp-software': '8109', 'exp-bank': '8109', 'exp-repair': '8109', 'exp-contractor': '8109', 'exp-food': '8109', 'exp-training': '8109' });

/**
 * خدمتِ دوره‌دارِ یک شیء: «بیمهٔ (یک‌سالهٔ) انبار»، «اجارهٔ شش‌ماههٔ انبار»،
 * «بیمهٔ کالاهای انبار»، «کرایهٔ انبار».
 *
 * عبارت قوی «بیمه انبار» فقط چسبیده تطبیق می‌خورد؛ صفت دوره یا کسرهٔ اضافه
 * («بیمه یک ساله انبار»، «بیمه ی انبار») آن را می‌شکست و «انبار»ِ مواد و کالا با
 * «بیمه» مساوی می‌شد و به‌خاطر ترتیب تعریف برنده می‌شد — پیش‌پرداخت و هزینهٔ
 * ماهانهٔ بیمه روی «مواد و کالا» می‌نشست. در زنجیرهٔ اضافه، اسمِ اول هسته است:
 * انبار و کالا اینجا مفعولِ خدمت‌اند، نه خریدِ کالا. حرف ربط و اضافه («و، به،
 * از، تا، برای، بابت …») زنجیره را می‌شکند: «بیمه ۱۲ میلیون دادیم و خرید کالا»
 * دو موضوع است و «کرایه تاکسی تا دفتر» حمل‌ونقل.
 */
const SERVICE_HEAD = '(?:بیمه|بیمع|اجاره|کرایه)';
const CHAIN_WORD = '(?:\\s+(?!(?:و|به|از|با|رو|را|که|هم|تا|برای|واسه|بابت|جهت)(?![آ-ی]))\\S+){0,4}?';
const GOODS_OBJECT = '(?:انبار|کالا|کالاها|کالاهای|موجودی|اجناس)(?![آ-ی])';
export const SERVICE_OF_GOODS = new RegExp(`(?<![آ-ی])(${SERVICE_HEAD}${CHAIN_WORD})\\s+${GOODS_OBJECT}`, 'g');
// «بیمهٔ حمل‌ونقل»، «بیمهٔ یک‌سالهٔ باربری»: بار و حملی که بیمه شده مفعولِ بیمه است،
// نه کرایهٔ حمل؛ وگرنه «بیمه» و «حمل‌ونقل» مساوی می‌شدند و پیش‌پرداخت بیمه به حسابدار می‌رفت.
const CARGO_OBJECT = '(?:حمل|باربری|ترابری|محموله|بار)(?![آ-ی])';
export const INSURANCE_OF_CARGO = new RegExp(`(?<![آ-ی])((?:بیمه|بیمع)${CHAIN_WORD})\\s+${CARGO_OBJECT}(?:\\s+و\\s+نقل)?`, 'g');
const pattern = (head, source) => ({ head, pattern: new RegExp(source) });
// «بیمهٔ یک‌سالهٔ انبار» و «کرایهٔ شش ماه مغازه»: هسته با فاصلهٔ چند واژه.
const INSURED_GOODS = pattern('بیمه', `(?<![آ-ی])(?:بیمه|بیمع)${CHAIN_WORD}\\s+${GOODS_OBJECT}`);
const RENTED_PREMISES = pattern('اجاره', `(?<![آ-ی])(?:اجاره|کرایه)${CHAIN_WORD}\\s+(?:انبار|مغازه|دفتر|سوله|کارگاه|خانه|خونه|ملک|واحد|ساختمان|غرفه)(?![آ-ی])`);

function rule(id, name, type, chartCode, groups) {
  const keywords = [];
  for (const [weight, words] of groups) {
    for (const word of words) keywords.push(word.pattern ? { word: word.head, pattern: word.pattern, weight } : { word: normalizePersian(word), weight });
  }
  return Object.freeze({ id, name, type, chartCode, legacyChartCode: LEGACY_CHART_CODES[id] || null, keywords: Object.freeze(keywords) });
}

