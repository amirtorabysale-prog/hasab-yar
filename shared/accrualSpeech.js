import { normalizePersian } from './normalize.js';
/**
 * نشانهٔ «پول هنوز جابه‌جا نشده».
 *
 * جهت ب — مصرف پیش از پرداخت — قاعده‌اش ساخته شده، ولی تشخیصش نیاز به یک
 * واقعیت دارد که پارسر بیرون نمی‌کشید: قبضی که آمده و هنوز پرداخت نشده،
 * هزینهٔ **دورهٔ مصرف** است و یک بدهی می‌سازد، نه یک پرداخت نقدی.
 *
 * عمداً محافظه‌کارانه: فقط وقتی جمله **صریح** بگوید پول نرفته. «قبض اومده»
 * به‌تنهایی مبهم است — می‌تواند همان لحظه پرداخت هم شده باشد — و حدس‌زدنش
 * یعنی یک پرداخت انجام‌شده به بدهی تبدیل می‌شود و ماندهٔ بانک غلط می‌ماند.
 *
 * یک مرز که در آزمون صوتی خودش را نشان داد: «هنوز هیچی فاکتور نکرده» دربارهٔ
 * فاکتور است، نه پرداخت. آن جمله یک پیش‌پرداخت **انجام‌شده** را توصیف می‌کند.
 */

const GAP = '[\\s\\u200c]*';
const YA = '[یي]';

const UNPAID = new RegExp([
  // «هنوز پولش رو ندادم»، «هنوز پرداخت نشده».
  //
  // فعل منفی باید خودِ پرداخت باشد. «هنوز» تنها با هر «نشده»ای کافی نبود و در
  // آزمون استرس دو پرداختِ انجام‌شده را بدهی کرد: «بیست میلیون بیعانه دادم…
  // هنوز معامله قطعی نشده» و «صد میلیون دادیم به پیمانکار… هنوز تموم نشده».
  // هر دو پول رفته بود؛ آنچه نشده بود، معامله و کار بود.
  `هنوز[^.،؛!؟]{0,18}ن(?:دادم|دادیم|داد${YA}م|پرداختم|ر${YA}ختم|ر${YA}خت${YA}م|زدم|زد${YA}م)`,
  `هنوز[^.،؛!؟]{0,12}(?:پرداخت|تسو${YA}ه|وار${YA}ز)${GAP}ن(?:شده|کرده|کردم|کرد${YA}م)`,
  // «موعد پرداختش ...»
  `موعد${GAP}پرداخت`,
  // «باید بدم»، «قراره پرداخت کنم»
  `با${YA}د${GAP}(?:بهش${GAP})?بد(?:م|${YA}م)`,
  `قراره${GAP}پرداخت`,
  `پرداخت${GAP}نکرد(?:م|${YA}م)`,
  `پرداخت${GAP}نشده`,
].join('|'));

// «سررسید» فقط وقتی دربارهٔ بدهی خودِ ماست که از چک و سفته حرف نزند: «چک
// صیادی به سررسید سه ماه بعد به ما واگذار کرد» پرداخت‌نشده نیست، ابزار پرداخت
// است — و در آزمون استرس همین جمله بدهی قطعی شد.
const DUE_DATE = new RegExp(`سررس${YA}د`);
const INSTRUMENT = /چک|سفته|برات/;

/**
 * پرداختی که ما بعداً می‌کنیم. الگوی «قراره پرداخت» فقط شکلِ چسبیده را می‌شناخت و «قبض برق
 * مهر … اومده ولی قراره تا آبان پرداختش کنیم» خروج نقدیِ امروز ثبت می‌شد (T18، دور سخت).
 * فقط اول‌شخص («کنیم»، «بدیم»، «می‌دیم»): وعدهٔ مشتری و مستاجر («قراره بده») مسیر طلب است
 * (`payerNotYet` در پارسر). «قرار بود» گذشته است و چیزی نمی‌گوید.
 */
const OBJ = '(?:ش|شو|شون|شونو|شان)?';
// «تحویلش میدیم»، «جواب می‌دیم»، «سفارش بدیم»: دادنِ کار و کالا، نه پول.
const NOT_MONEY_BEFORE = `(?<!(?:تحو${YA}ل|انجام|جواب|خبر|قول|اجازه|سفارش|جنس|بار|کالا|کار)(?:ش|شو|شون|شان|ها|و)?(?:\\s+(?:رو|را))?\\s+)`;
const WE_WILL_PAY = `(?:${NOT_MONEY_BEFORE}(?:بد(?:${YA}م|م)|بپرداز(?:${YA}م|م)|بر${YA}ز(?:${YA}م|م))|(?:پرداخت|وار${YA}ز|تسو${YA}ه)${OBJ}${GAP}کن(?:${YA}م|م))${OBJ}(?![آ-ی])`;
const FUTURE_PAYMENT = new RegExp([
  // «قراره تا آبان پرداختش کنیم»، «قرار است آخر ماه بپردازیم»، «قرار شده هفته بعد بدیم».
  `(?<![آ-ی])قرار(?:ه|${GAP}است|${GAP}شده)(?:\\s+\\S+){0,8}?\\s+${WE_WILL_PAY}`,
  // «باید تا پنجم آبان بدیم».
  `(?<![آ-ی])با${YA}د(?:\\s+\\S+){0,8}?\\s+${WE_WILL_PAY}`,
  // «ماه بعد پرداخت می‌کنیم»، «میدیم هفته دیگه»، «تا آبان پرداختش می‌کنیم».
  `(?<![آ-ی])(?:${NOT_MONEY_BEFORE}م${YA}${GAP}(?:د(?:${YA}م|م)|پرداز(?:${YA}م|م)|ر${YA}ز(?:${YA}م|م))${OBJ}|(?:پرداخت|وار${YA}ز|تسو${YA}ه)${OBJ}${GAP}(?:م${YA}${GAP}کن(?:${YA}م|م)|خواه${YA}م${GAP}کرد)|خواه${YA}م${GAP}پرداخت)(?![آ-ی])`,
].join('|'));
/**
 * پرداختِ آینده فقط وقتی بدهی است که هزینه همین حالا واقع شده: قبض یا فاکتور آمده، کار
 * تمام شده، حقوقِ ماهِ گذشته‌شده. «اجاره دفتر رو ماه بعد ۱۰ میلیون میدیم» پولِ آینده برای
 * خدمتِ آینده است؛ هنوز بدهی‌ای نیست و موتور دورهٔ خدمت را می‌پرسد (engine5-p2).
 */
const INCURRED = new RegExp(`قبض|قبوض|فاکتور|صورت${GAP}حساب|(?<![آ-ی])(?:اومد|آمد|رس${YA}د|صادر${GAP}شد)(?:ه)?(?![آ-ی])|بدهکار|(?:تموم|تمام|انجام)${GAP}(?:شده|شد)(?![آ-ی])|حقوق${GAP}(?:فرورد${YA}ن|ارد${YA}بهشت|خرداد|ت${YA}ر|مرداد|شهر${YA}ور|مهر|آبان|آذر|د${YA}|بهمن|اسفند|ا${YA}ن${GAP}ماه|ماه${GAP}(?:قبل|گذشته|پ${YA}ش))`);
// «پرداختش نکردیم»: ضمیر مفعولی پیش از فعل منفی؛ گذشته است و نشانهٔ هزینهٔ واقع‌شده نمی‌خواهد.
const NOT_PAID_WITH_OBJECT = new RegExp(`(?:پرداخت|تسو${YA}ه|وار${YA}ز)${OBJ}${GAP}نکرد(?:م|${YA}م)`);
// پولِ انجام‌شده، با مرزِ واژه: «ندادیم» و «نکردیم» این نیستند. «قرار بود آبان بدیم ولی
// امروز دادیم» پرداخت شده است.
const PAID_DONE = new RegExp(`(?<![آ-ی])(?:داد(?:${YA}م|م)|ر${YA}خت(?:${YA}م|م)|زد(?:${YA}م|م)|(?:پرداخت|وار${YA}ز|تسو${YA}ه)${OBJ}${GAP}(?:شد|کرد(?:${YA}م|م)))${OBJ}(?![آ-ی])`);
const PAID_NOW = new RegExp(`(?:داد${YA}م|دادم|ر${YA}خت${YA}م|ر${YA}ختم|زد${YA}م|پرداخت${GAP}(?:شد|کرد${YA}م|کردم)|وار${YA}ز${GAP}(?:شد|کرد${YA}م|کردم)|کسر${GAP}شد|تسو${YA}ه${GAP}(?:شد|کرد${YA}م|کردم))`);

export function readUnpaidSignal(input) {
  const text = normalizePersian(String(input || ''));
  if (!/هنوز|موعد|سررس|بدم|بدیم|نکرد|نشده|قرار|باید|م[یي]\s*(?:د|پرداز|ر[یي]ز|کن)|خواه[یي]م|بپرداز|بر[یي]ز/.test(text)) return false;
  if (UNPAID.test(text)) return true;
  if (NOT_PAID_WITH_OBJECT.test(text)) return true;
  if (FUTURE_PAYMENT.test(text) && INCURRED.test(text) && !PAID_DONE.test(text)) return true;
  // «قسط اول سررسید شد، بیست و سه میلیون قسط دادیم» پرداخت شده است؛ سررسید
  // فقط وقتی نشانهٔ بدهیِ باز است که پرداختی هم گفته نشده باشد.
  return DUE_DATE.test(text) && !INSTRUMENT.test(text) && !PAID_NOW.test(text);
}
