/**
 * نشانهٔ «پول هنوز جابه‌جا نشده».
 *
 * جهت ب — مصرف پیش از پرداخت — قاعده‌اش ساخته شده، ولی تشخیصش نیاز به یک
 * واقعیت دارد که پارسر بیرون نمی‌کشید: قبضی که آمده و هنوز پرداخت نشده،
 * هزینهٔ **دورهٔ مصرف** است و یک بدهی می‌سازد، نه یک پرداخت نقدی.
 *
 * عمداً محافظه‌کارانه: فقط وقتی جمله **صریح** بگوید پول نرفته. «قبض اومده»
 * به‌تنهایی مبهم است — می‌تواند همان لحظه پرداخت هم شده باشد — و حدس‌زدنش
 * یعنی یک پرداخت انجام‌شده به بدهی تبدیل می‌شود و ماندهٔ بانک غلط می‌ماند.
 *
 * یک مرز که در آزمون صوتی خودش را نشان داد: «هنوز هیچی فاکتور نکرده» دربارهٔ
 * فاکتور است، نه پرداخت. آن جمله یک پیش‌پرداخت **انجام‌شده** را توصیف می‌کند.
 */

const GAP = '[\\s\\u200c]*';
const YA = '[یي]';

const UNPAID = new RegExp([
  // «هنوز پرداخت نشده»، «هنوز ندادم»، «هنوز پولش رو ندادم».
  //
  // فاصلهٔ کوتاه میان «هنوز» و فعل منفی پذیرفته می‌شود — گفتار محاوره‌ای
  // تقریباً همیشه چیزی وسطش می‌گذارد — ولی از مرز جمله رد نمی‌شود، وگرنه
  // «هنوز نیامده، ولی پرداخت کردم» هم پرداخت‌نشده خوانده می‌شد.
  `هنوز[^.،؛!؟]{0,18}ن(?:شده|کردم|کرد${YA}م|دادم|داد${YA}م|پرداخت)`,
  // «موعد پرداختش ...»، «سررسیدش ...»
  `موعد${GAP}پرداخت`,
  `سررس${YA}د`,
  // «باید بدم»، «قراره پرداخت کنم»
  `با${YA}د${GAP}(?:بهش${GAP})?بد(?:م|${YA}م)`,
  `قراره${GAP}پرداخت`,
  `پرداخت${GAP}نکرد(?:م|${YA}م)`,
  `پرداخت${GAP}نشده`,
].join('|'));

export function readUnpaidSignal(input) {
  const text = String(input || '');
  if (!/هنوز|موعد|سررس|بدم|بدیم|نکرد|نشده/.test(text)) return false;
  return UNPAID.test(text);
}
