/**
 * «این پول بابت چه بود؟» — وقتی خودِ جمله جوابش را داده.
 *
 * موتور تصمیم، وقتی دسته عمومی است، این را از ثبت‌کننده می‌پرسد. ولی پرسیدن
 * از کسی که همین حالا گفته «دویست میلیون وام گرفتیم» یا «معلوم نیست از
 * کیه»، سؤالی است که جوابش در جمله بود. اینجا فقط نشانه‌های صریح خوانده
 * می‌شوند؛ هرچه صریح نیست، همان سؤال می‌ماند.
 *
 * الگوها روی متن خام اجرا می‌شوند و نرمال‌سازی صدا زده نمی‌شود؛ این مسیر در
 * ثبت اجرا می‌شود، نه در تایپ زنده، ولی ارزان ماندنش خرجی ندارد.
 */
import { readPettyCash } from './pettyCashSpeech.js';
import { normalizePersian } from './normalize.js';
import { detectPartnerFundedSpend } from './partnerPaidSpeech.js';
import { isContractInstalment, readsContractRemainder } from './priorSettlement.js';
import { moneyReturned } from './refundSpeech.js';

// همهٔ الگوهای این فایل روی متن یکدست‌شده اجرا می‌شوند: «کهنهٔ» با همزه، ی و ک
// عربی و نیم‌فاصله هر کدام یک الگو را بی‌صدا از کار می‌انداختند.
const clean = (input) => normalizePersian(String(input || ''));

const GAP = '[\\s\\u200c]*';

/** وام یا تسهیلات گرفته شد — نه «قسط وام دادیم». */
const LOAN_IN = new RegExp(`(?:وام|تسهیلات|قرض${GAP}(?:الحسنه)?)${GAP}(?:[^.؛،]{0,30}?)(?:گرفت|دریافت${GAP}(?:کرد|شد)|واریز${GAP}(?:شد|کرد))`);
const LOAN_OUT = new RegExp(`قسط|بازپرداخت|پس${GAP}داد|تسویهٔ?${GAP}وام`);

/** صریحاً گفته شده منشأ را نمی‌داند. */
const UNKNOWN_ORIGIN = new RegExp([
  `(?:معلوم|مشخص)${GAP}نیست?${GAP}(?:از${GAP})?(?:طرف${GAP})?(?:کی|کیه|کیست|کجا|چه${GAP}کسی)`,
  `نمی${GAP}(?:دونیم|دونم|دانیم|دانم)${GAP}(?:از${GAP})?(?:طرف${GAP})?(?:کی|کیه|کیست|کجا)`,
  `ناشناس`,
].join('|'));

const BANK_INTEREST = new RegExp(`سود${GAP}(?:بانکی|سپرده|حساب)`);
const CAPITAL_IN = new RegExp(`افزایش${GAP}سرمایه|آورده${GAP}(?:مالک|شریک|نقدی)|سرمایه${GAP}(?:گذاشت|آورد)`);

/** برداشت برای خودِ مالک — نه «از بانک برداشت کردیم» که انتقال است. */
const OWNER_DRAWING = new RegExp([
  `(?:خرج|مصرف|استفاده|کار)${GAP}(?:ی${GAP})?شخصی`,
  `برداشت${GAP}شخصی`,
  `برداشت${GAP}(?:مالک|صاحب${GAP}کار)`,
].join('|'));

export function receiptPurposeFromSpeech(input) {
  const text = clean(input);
  if (!text) return null;
  if (UNKNOWN_ORIGIN.test(text)) return 'unknown';
  if (LOAN_IN.test(text) && !LOAN_OUT.test(text.replace(/قسط[^.؛،]*(?:شروع|بعد|آینده)/g, ''))) return 'loan';
  if (CAPITAL_IN.test(text)) return 'owner';
  if (BANK_INTEREST.test(text)) return 'other-income';
  return null;
}

/**
 * مساعده: پولی که به کارمند داده شده و از حقوق بعدی‌اش کم می‌شود.
 *
 * هزینهٔ حقوق نیست — حقوقِ آن ماه هنوز تحقق نیافته — و پرداخت حقوق هم نیست
 * که کسور بیمه و مالیات بخواهد. طلب شرکت از همان کارمند است.
 */
const EMPLOYEE_ADVANCE = new RegExp([
  `مساعده`, `علی${GAP}ا?لحساب${GAP}حقوق`, `پیش${GAP}(?:پرداخت${GAP})?حقوق`,
  `(?:وام|قرض)${GAP}(?:به${GAP})?(?:کارمند|کارگر|پرسنل|همکار)`,
].join('|'));

export function paymentPurposeFromSpeech(input) {
  const text = clean(input);
  if (!text) return null;
  if (EMPLOYEE_ADVANCE.test(text)) return 'employee-advance';
  if (OWNER_DRAWING.test(text)) return 'owner-drawing';
  // «۳۰ میلیون پول پیش مغازه رو دادیم» سؤال «بابت چه بود؟» می‌گرفت.
  if (paidPropertyDeposit(text)) return 'deposit';
  return null;
}

/**
 * ودیعه، رهن و «پول پیش»ِ ملک — پولی که به حکم نامش برمی‌گردد.
 *
 * در عرف اجارهٔ ایران ودیعه و رهن و پول پیش یک چیزند: پولی که موجر نگه
 * می‌دارد و آخر قرارداد پس می‌دهد. پرسیدن «قابل استرداد است یا مصرف می‌شود؟»
 * از کسی که همین حالا گفته «ودیعه»، سؤالی است که جوابش در جمله بود؛ و برگه‌ای
 * که آن را «پرداخت بابت اجاره» می‌خواند، همان خطایی است که مالک محصول دید
 * («سیستم هنوز ودیعه رو به‌عنوان اجاره تشخیص می‌ده»، مهر ۱۴۰۵).
 *
 * «سپرده»، «تضمین» و «حسن انجام کار» این‌جا نیستند: سپرده نامِ حساب بانکی هم
 * هست و ضمانت‌نامه گاهی پولی جابه‌جا نمی‌کند؛ آن‌ها همان سؤال را می‌گیرند.
 * «رهنی»، «رهنما» و «رهنمود» رهن نیستند. «پول پیش» فقط کنار نشانهٔ ملک یا اجاره
 * ودیعه است؛ «پول پیش ما مونده» نگه‌داری پول است.
 */
const DEPOSIT_NAME = new RegExp(`(?<![آ-ی])(?:ودیع(?:[هة]|ش)|رهن(?:ش|شو|و|رو)?(?![آ-ی]))`);
const PROPERTY_ADVANCE = new RegExp(`(?<![آ-ی])پول${GAP}پیش(?![آ-ی])(?!${GAP}(?:ما|من|شما|اون|او|ایشون|خودم|خودمون|حسابدار|شریک|بانک)(?![آ-ی]))`);
const PROPERTY_CONTEXT = /اجاره|کرایه|مغازه|خونه|خانه|دفتر|انبار|سوله|کارگاه|واحد|ملک|آپارتمان|موجر|مستاجر|مستأجر/;
/** ودیعه‌ای که بخشی از اجاره می‌شود: «از اجاره کم می‌شه»، «تبدیل به اجاره». */
const DEPOSIT_CONSUMED = /(?:کم|کسر|تبدیل|جای)[^.،؛\n]{0,25}اجاره|اجاره[^.،؛\n]{0,25}(?:کم|کسر|تبدیل)/;

/** نام ودیعهٔ ملک در جمله، هر جهتی که پول رفته باشد. */
export function mentionsPropertyDeposit(input) {
  const text = clean(input);
  return DEPOSIT_NAME.test(text) || (PROPERTY_ADVANCE.test(text) && PROPERTY_CONTEXT.test(text));
}

/**
 * ودیعهٔ تازه — نه برگشتش («صاحبخونه ودیعه رو پس داد» برگشت قرارداد است و
 * مسیر خودش را دارد) و نه ودیعه‌ای که به اجاره تبدیل یا از آن کم می‌شود.
 */
function paidPropertyDeposit(input) {
  const text = clean(input);
  return mentionsPropertyDeposit(text) && !moneyReturned(text) && !DEPOSIT_CONSUMED.test(text);
}

/**
 * وام‌دهنده، وقتی جمله گفته «از بانک X وام گرفتیم».
 *
 * طرف حساب وام همان بانک است؛ بدون آن، بدهی وام بی‌نام می‌ماند و تفکیک
 * وام‌های دو بانک ممکن نیست.
 */
const LENDER = new RegExp(`از${GAP}(بانک${GAP}[آ-ی]+)`);
export function lenderFromSpeech(input) {
  const match = LENDER.exec(clean(input));
  return match ? match[1].replace(/[\s‌]+/g, ' ').trim() : null;
}

/**
 * جمله‌ای که خودش می‌گوید قضاوت لازم است.
 *
 * سؤال گزینه‌ای فقط وقتی کمک می‌کند که جواب درست یکی از گزینه‌ها باشد و
 * ثبت‌کننده آن را بداند. این‌ها چنین نیستند:
 *
 * - **تردید:** «نمی‌دونم»، «بعداً میگم چی بود»، «چطور ثبت کنیم؟». گزینهٔ
 *   «هزینهٔ جاری» برای کسی که فقط می‌خواهد «تراز به هم نریزد» وسوسهٔ ثبت
 *   غلط است.
 * - **مشکوک یا پنهان‌کاری:** «مبلغ مشکوک… بزن به درآمد که کسی نفهمه». گزینهٔ
 *   «درآمد متفرقه» دقیقاً همان کاری است که نباید شود.
 * - **شریک و سهامدار:** آورده، قرض شریک یا برداشت؟ جایش جاری شرکاست و
 *   حسابدار تعیین می‌کند.
 * - **تسویهٔ قبلی، اصل و فرع وام، استرداد مالیات، لیست بیمه، جریمه:** هرکدام
 *   سند مبنا یا تفکیک مبلغ می‌خواهند و انتخاب «فروش» یا «هزینه» یعنی شناسایی
 *   دوباره.
 * - **فروش دارایی شرکت:** «وانت شرکت که قیمت دفتریش… رو فروختیم» درآمد عادی
 *   نیست؛ سود و زیان فروش دارایی و حذف استهلاک انباشته است.
 * - **سهم‌بندی مبلغ:** «بیست میلیون دادم، ده تومنش مال کرایهٔ عقب‌افتاده» یک
 *   رویداد با دو ماهیت است.
 *
 * خروجی، دلیلِ کوتاه به زبان حسابدار است؛ نبودِ نشانه یعنی `null`.
 */
const UNCERTAIN = new RegExp([
  `نمی${GAP}(?:دونم|دانم|دونیم|دانیم)`, `نمیدونم`, `بعدا${GAP}(?:بهت${GAP})?(?:میگم|می${GAP}گم|میگیم)`,
  // «احتمالاً مال خانم توکلیه، ولی مطمئن نیستیم»: حدسِ خودِ گوینده، مبنای فروش نیست.
  `مطمئن${GAP}نیست(?:م|یم|ن)?`, `احتمالا`, `(?<![آ-ی])شاید(?![آ-ی])`, `نگاه${GAP}کن${GAP}(?:تو|در)${GAP}سیستم`, `(?:چطور|چجوری|چه${GAP}جوری)${GAP}ثبت`,
].join('|'));
const SUSPICIOUS = /مشکوک|کسی\s*نفهمه|نفهمن|پنهان|زیر\s*میزی/;
const PARTNER = /شریک|سهامدار|سهام\s*دار/;
// «تسویه» به‌تنهایی نشانه نیست: «شارژ شش ماه جلوتر رو تسویه کردم» پیش‌پرداخت است.
const PRIOR_SETTLEMENT = /تسویه\s*(?:بدهی|طلب|حساب|فاکتور)|بدهی\s*قبلی|طلب\s*قبلی|بدهکار\s*بودیم|(?:خرید|فاکتور|بدهی|طلب)\s*(?:\S+\s*)?ماه\s*قبل|فاکتور\s*قبلی/;
// «قسطی میدیم/خریدیم» قسط وام نیست: باقی مبلغ یک خرید یا قرارداد، بدهی به
// همان فروشنده یا بیمه‌گر است و اصل و سودی ندارد. «قسط» به‌تنهایی (بی‌قرارداد)
// همچنان قسط وام خوانده می‌شود.
const LOAN_SERVICE = /اصل\s*(?:وام|تسهیلات)|قسط(?!ی)|(?:وام|تسهیلات|لیزینگ)[^.؛،]{0,30}قسطی/;
const ON_INSTALMENTS = /(?<![آ-ی])قسطی(?![آ-ی])/;
const TAX_REFUND = /(?:مالیات|ارزش\s*افزوده)[^.؛]*(?:استرداد|اضافه\s*پرداخت|برگشت)/;
const PAYROLL_LIST = /لیست\s*بیمه|تامین\s*اجتماعی|تأمین\s*اجتماعی/;
const ASSET_DISPOSAL = /(?:قیمت|ارزش)\s*دفتری|(?:وانت|ماشین|خودرو|دستگاه|تجهیزات|اموال|سوله)\s*(?:\S+\s*){0,3}(?:شرکت|دفتر|کارگاه)\s*(?:\S+\s*){0,6}?(?:رو|را)?\s*فروختیم/;
// «پرینتر قدیمی دفتر رو ۳ میلیون فروختیم» فروش کالا ثبت می‌شد. وسیلهٔ کارکرده
// یا وسیلهٔ خودِ دفتر، کالای فروش نیست؛ «سه تا پرینتر به مشتری فروختیم» هست.
const USED_ASSET_SALE = /(?<![آ-ی])(?:وانت|ماشین|خودرو|دستگاه|پرینتر|چاپگر|کامپیوتر|رایانه|لپ\s*تاپ|میز|صندلی|کولر|یخچال|مبلمان|لیفتراک|کامیون|موتورسیکلت)(?:\s*\S+){0,3}?\s*(?:قدیمی|کهنه|دست\s*دوم|مستعمل|کارکرده|اسقاطی|شرکت|دفتر|کارگاه|خودمون)(?![آ-ی])(?:\s*\S+){0,8}?\s*فروخت(?:یم|م)(?![آ-ی])/;
const PORTION = /(?:تومنش|تومانش|میلیونش|هزارش)\s*(?:مال|بابت|برای)|بقیه(?:\s*اش|ش)?\s*(?:مال|بابت|برای)/;
// برگشت از فروش یا خرید: کم‌کردن فروش قبلی است، نه دریافت یا پرداخت تازه.
// «از مواد اولیه‌ای که خریده بودیم پس دادیم» خرید تازهٔ موجودی ثبت می‌شد.
// یک مفهوم، نه یک عبارت: «پس/عودت/مرجوع» + «داد/فرستاد/آورد/کرد» در هر صیغه.
// «پس بدیم» (آینده) برگشت نیست.
const RETURNED = /مرجوع|برگشت\s*از\s*(?:فروش|خرید)|برگردوند|برگرداند|(?<![آ-ی])(?:پس|عودت)\s*(?:داد|فرستاد|آورد|کرد|زد)(?:یم|م|ن|ند|ه)?(?![آ-ی])/;
// ضایعات و اسقاط درآمد فروش نیست؛ «سایر درآمدها»ست و گاهی موجودی را هم کم می‌کند.
const SCRAP = /ضایعات|اسقاط|آهن\s*قراضه/;
// ضمانت‌نامه و وثیقه: مبلغ اسمی‌شان پول جابه‌جاشده نیست و ثبتشان انتظامی است.
const GUARANTEE = /ضمانت[\s‌]*نامه|وثیقه|تضمین|سپرده[\s‌]*(?:نقدی|حسن)/;

// «قرارداد بیمه یکساله ۱۲ میلیونی با بیمه ایران زدیم»، «قولنامه اجاره رو
// بستیم»: قرارداد امضا شد؛ مبلغ ارزش قرارداد است و جمله نمی‌گوید پولی رفته یا
// آمده. ثبتش به‌عنوان پرداخت، ردیف نقدی برای پولی می‌ساخت که جابه‌جا نشده. فقط
// وقتی جمله خودِ پرداخت را هم بگوید («… دادیم»، «کارت به کارت زدیم»، «واریز
// کردیم») رویداد پولی است.
const CONTRACT_SIGNED = /(?:قرارداد|قولنامه|اجاره\s*نامه|بیمه\s*نامه)(?:[^.؛]*?)(?<![آ-ی])(?:(?:زد|بست)(?:یم|م|ن|ند)?|امضا\s*(?:کرد|شد)(?:یم|م|ن|ند)?|منعقد\s*(?:کرد|شد)(?:یم|م|ن|ند)?)(?![آ-ی])/;
const MONEY_MOVED = /(?<![آ-ی])(?:داد|ریخت|پرداخت|واریز|کشید|گرفت|دریافت|فرستاد)(?:یم|م|ن|ند)?(?![آ-ی])|پرداخت|واریز|کارت|پول|نقد|چک|انتقال|پایا|ساتنا|(?:از|به|تو|توی)\s*حساب|بیعانه|پیش\s*پرداخت|علی\s*الحساب/;
// «۵۰ میلیون ضرر زدیم»: زیانِ یک کار است، نه پولی که به کسی پرداخت شد.
const LOSS_STATEMENT = /(?<![آ-ی])(?:ضرر|زیان)\s*(?:زد|کرد|دید|خورد|داشت)(?:یم|م)(?![آ-ی])/;

export function judgmentReason(input, { amount } = {}) {
  const text = clean(input);
  if (!text) return null;
  // سدِ آخر: «تنخواه به رضایی دادیم» در مسیر ثبت روزانه هزینه یا پیش‌پرداخت
  // خوانده می‌شد. برگهٔ «پرداخت تنخواه» جلوتر جلویش را می‌گیرد؛ اگر از آن رد شد،
  // دست‌کم به حسابدار برود نه به گزینه‌هایی که هیچ‌کدام درست نیست.
  if (readPettyCash(text)?.action === 'fund') return 'پرداخت یا شارژ تنخواه هزینه نیست؛ انتقال از صندوق یا بانک به حساب تنخواه است و از صفحهٔ «تنخواه‌گردان» ثبت می‌شود.';
  if (CONTRACT_SIGNED.test(text) && !MONEY_MOVED.test(text)) return 'جمله امضای قرارداد را می‌گوید، نه پرداخت یا دریافت؛ مبلغ ارزش قرارداد است و تا پولی جابه‌جا نشده ردیف نقدی ساخته نمی‌شود. حسابدار قرارداد و بدهی یا طلبش را ثبت می‌کند.';
  if (LOSS_STATEMENT.test(text)) return 'زیانِ گفته‌شده نتیجهٔ یک کار است، نه پولی که جابه‌جا شد؛ حسابدار منشأ آن را ثبت می‌کند.';
  if (SUSPICIOUS.test(text)) return 'جمله از مبلغ مشکوک یا پنهان‌کاری می‌گوید؛ ثبتش قضاوت حسابدار لازم دارد.';
  if (UNCERTAIN.test(text) && !UNKNOWN_ORIGIN.test(text)) return 'ثبت‌کننده خودش گفته ماهیت را نمی‌داند؛ حسابدار تعیین می‌کند.';
  // «آقای رضایی شریکمون اجاره شش ماهه دفتر رو از جیب خودش داد»: پرداخت‌کننده و
  // جهت هر دو گفته شده — شرکت به شریک بدهکار شد، همان چیزی که با «مدیرعامل»
  // هم ثبت می‌شود. نشانهٔ شریک فقط وقتی قضاوت است که آورده، قرض یا برداشت بودن
  // معلوم نباشد. مسیر AI همین را در `understandingPlan` می‌کند.
  if (PARTNER.test(text) && !detectPartnerFundedSpend(input)) return 'پای شریک یا سهامدار در میان است؛ آورده، قرض یا برداشت بودنش را حسابدار تعیین می‌کند.';
  if (PRIOR_SETTLEMENT.test(text)) return 'به طلب، بدهی یا فاکتور قبلی اشاره دارد؛ شناسایی دوبارهٔ درآمد یا هزینه نباید رخ دهد.';
  // «قسط دوم بیمه/اجاره» قسط وام نیست؛ اصل و سودی ندارد و به قرارداد موجود
  // برمی‌گردد. برچسب «وام» ماهیت را غلط به حسابدار می‌گفت.
  // با `amount`، فقط اگر همان ردیف جملهٔ چندپرداختی باشد.
  const contractPart = readsContractRemainder(text, { amount });
  if (contractPart) {
    return contractPart === 'instalment'
      ? 'قسطی از یک قرارداد (بیمه، اجاره، اشتراک) است؛ کل مبلغ قرارداد، بدهی باقی و دورهٔ پوشش را حسابدار با سند مبنا ثبت می‌کند، نه یک پیش‌پرداخت تازه.'
      : 'باقی یا قسط بعدیِ یک قرارداد موجود است؛ بدهی یا طلب همان قرارداد بسته می‌شود و دورهٔ پوشش تازه‌ای ساخته نمی‌شود.';
  }
  // «حقوق ۴۰ میلیون دادیم، قسط دوم بیمه ۳ میلیون هم دادیم»: «قسط» مال ردیف بیمه
  // است؛ ردیف حقوق را «قسط وام» نامیدن ماهیتش را غلط می‌گفت. ردیف دیگرِ همان
  // جمله هم به حسابدار می‌رود: پارسر دسته و دورهٔ هر ردیف را از تکهٔ کنار مبلغ
  // می‌خواند و در این جمله‌ها «بیمه»ی ردیف قسط به ردیف حقوق یا اجاره هم می‌رسد —
  // پرسیدن «پوشش بیمه از کِی؟» برای حقوق، یا پیش‌پرداخت با حساب غلط، حدس است.
  if (amount != null && readsContractRemainder(text)) {
    return 'این جمله چند پرداخت دارد و یکی از آن‌ها باقی یا قسطِ یک قرارداد موجود است؛ حسابدار ردیف‌ها را از هم جدا و هر کدام را به سند خودش وصل می‌کند.';
  }
  if (LOAN_SERVICE.test(text) && !LOAN_IN.test(text) && !isContractInstalment(text)) return 'قسط یا اصل وام، اصل و سود جدا دارد؛ حسابدار تفکیک می‌کند.';
  if (ON_INSTALMENTS.test(text)) return 'باقی مبلغ قسطی پرداخت می‌شود؛ بدهی باقی‌مانده به همان طرف را حسابدار با سند مبنا ثبت می‌کند — وام نیست.';
  if (TAX_REFUND.test(text)) return 'استرداد مالیات طلب قبلی را می‌بندد؛ حسابدار با سند مبنا تطبیق می‌دهد.';
  if (PAYROLL_LIST.test(text)) return 'پرداخت لیست بیمه، بدهی حقوق را تسویه می‌کند و سهم کارفرما و کارکنان دارد.';
  if (ASSET_DISPOSAL.test(text) || USED_ASSET_SALE.test(text)) return 'فروش دارایی شرکت درآمد عادی نیست؛ سود یا زیان فروش و استهلاک انباشته باید حساب شود.';
  if (PORTION.test(text)) return 'یک مبلغ چند بخش با ماهیت متفاوت دارد؛ تفکیکش با حسابدار است.';
  if (RETURNED.test(text)) return 'برگشت کالا، فروش یا خرید قبلی را کم می‌کند؛ دریافت یا پرداخت تازه نیست.';
  if (SCRAP.test(text)) return 'فروش ضایعات یا اسقاط درآمد فروش نیست؛ حسابدار حساب و اثر موجودی‌اش را تعیین می‌کند.';
  if (GUARANTEE.test(text)) return 'ضمانت‌نامه یا وثیقه مبلغ اسمی دارد که پول جابه‌جاشده نیست؛ ثبت انتظامی و سپرده را حسابدار تفکیک می‌کند.';
  return null;
}

/** «که آخر قرارداد پس می‌گیریم» — صریحاً می‌گوید پول برمی‌گردد. */
const RETURNS = new RegExp(`پس${GAP}می${GAP}(?:گیریم|گیرم|دن|دهند)|برمی${GAP}(?:گرده|گردد|گردونن)|مسترد|قابل${GAP}استرداد`);
export function saysRefundable(input) {
  const text = clean(input);
  if (/غیر\s*قابل\s*استرداد|قابل\s*استرداد\s*نیست/.test(text)) return false;
  if (RETURNS.test(text)) return true;
  // ودیعه و رهن و پول پیشِ ملک به حکم نامشان برمی‌گردند (`paidPropertyDeposit`).
  return paidPropertyDeposit(text) ? true : null;
}
