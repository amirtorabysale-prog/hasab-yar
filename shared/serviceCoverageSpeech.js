import { normalizePersian } from './normalize.js';

/**
 * کدام «مدت» دورهٔ پوشش یک خدمت است و کدام نیست.
 *
 * پیش‌پرداخت و پیش‌دریافت فقط برای خدمتِ دوره‌دار است: اجاره، بیمه، اشتراک،
 * لایسنس، پشتیبانی، نگهداری، شارژ، عضویت. هر مدتِ دیگری که در متن سند می‌آید
 * چیز دیگری را می‌گوید و کالا را به ماه‌های بعد نمی‌برد:
 *
 * - گارانتی/ضمانت کالا: «لپ تاپ با گارانتی یکساله»، «یخچال با گارانتی ۱۸ ماهه»،
 *   «… گارانتی و پشتیبانی یکساله» خرید یا فروش کالاست؛ گارانتی بخشی از خودِ کالاست، نه خدمتی جدا که ماه‌به‌ماه
 *   مصرف شود.
 * - شرط پرداخت: «تسویه شش ماه بعد»، «تسویه سه ماهه»، «اقساط شش ماهه»، «چک شش
 *   ماهه»، «نسیهٔ دو ماهه» زمانِ پول را می‌گوید، نه دورهٔ مصرف.
 *
 * این فایل هیچ وابستگی‌ای جز نرمال‌ساز ندارد تا موتور تصمیم و خواننده‌های سند
 * هر دو بی‌چرخهٔ import از آن بخوانند.
 */

const NUMBER_WORD = '(?:\\d{1,3}|یک|یه|دو|سه|چهار|پنج|شش|شیش|هفت|هشت|نه|ده|یازده|دوازده|پانزده|هجده|هیجده|بیست(?:\\s*و\\s*چهار)?|سی\\s*و\\s*شش|نیم)';
const LENGTH = `(?<![آ-ی])(?:${NUMBER_WORD}\\s*)?(?:ماهه|ساله|روزه|هفته\\s*ای|ماه|سال|روز|هفته)(?![آ-ی])(?:\\s*(?:بعد|بعدی|بعدش|آینده|اینده|دیگه|دیگر|آتی))?`;

// نام خدمتی که دوره دارد. «قرارداد» به‌تنهایی خدمت نیست («قرارداد فروش چای»).
const SERVICE_HEAD_WORDS = 'اجاره|کرایه|رهن|ودیعه|بیمه|بیمع|اشتراک|لایسنس|لاینسس|نرم\\s*افزار|هاست|هاستینگ|سرور|دامنه|آنتی\\s*ویروس|آبونمان|عضویت|پشتیبانی|نگهداری|خدمات|مشاوره|آموزش|نظافت|نگهبانی|سرایداری|تبلیغات|تبلیغ|شارژ|پوشش|سرویس\\s*(?:ابری|دهی|ماهانه|سالانه|نگهداری)';
const SERVICE_HEAD = new RegExp(`(?<![آ-ی])(?:${SERVICE_HEAD_WORDS})(?![آ-ی])`);
// واژهٔ میان نشانه و مدت: نه نام خدمت و نه فعل یا حرف اضافه‌ای که جمله را به
// پوشش برمی‌گرداند («چک دادیم برای شش ماه آینده» پوششِ اجاره است، نه مدت چک).
const FILLER = `(?!(?:${SERVICE_HEAD_WORDS}|برای|بابت|رو|را|دادیم|دادم|داد|دادن|کردیم|کردم|گرفتیم|گرفتم|پرداخت)(?![آ-ی]))`;
const ADJECTIVE_LENGTH = `(?<![آ-ی])(?:${NUMBER_WORD}\\s*)?(?:ماهه|ساله|روزه|هفته\\s*ای)(?![آ-ی])`;

const WARRANTY = new RegExp(`(?:(?<![آ-ی])با\\s+)?(?<![آ-ی])(?:گارانتی|گارانتي|وارانتی|ضمانت\\s*نامه|ضمانت|خدمات\\s*پس\\s*از\\s*فروش)(?![آ-ی])(?:\\s+و\\s+(?:پشتیبانی|خدمات|سرویس|تعویض)(?![آ-ی]))?(?:\\s+${FILLER}\\S+){0,2}?\\s*${LENGTH}`, 'g');
// «تسویه شش ماه بعد»، «تسویه سه ماهه»، «اقساط شش ماهه»، «مهلت پرداخت دو ماه».
const PAYMENT_TERM = new RegExp(`(?<![آ-ی])(?:تسویه|سررسید|سر\\s*رسید|مهلت\\s*پرداخت|مهلت|اقساط|اقساطی|قسطی|قسط|نسیه|(?:پرداخت|وصول)\\s+(?:به\\s*صورت|ظرف|طی|در|تا))(?![آ-ی])(?:\\s+${FILLER}\\S+){0,2}?\\s*${LENGTH}`, 'g');
// «چک شش ماهه»، «چک ۱۰ میلیونی دو ماهه»: مدت خودِ چک، فقط به شکل صفت.
const CHEQUE_TENOR = new RegExp(`(?<![آ-ی])چک(?![آ-ی])(?:\\s+(?:\\d+|[آ-ی]+ی|میلیون|تومن|تومان|هزار)(?![آ-ی])){0,3}?\\s*${ADJECTIVE_LENGTH}`, 'g');

/** متن بی‌مدت‌هایی که دورهٔ پوشش نیستند (گارانتی کالا و شرط پرداخت). */
export function withoutNonCoveragePeriods(input) {
  return normalizePersian(input).replace(WARRANTY, ' ').replace(PAYMENT_TERM, ' ').replace(CHEQUE_TENOR, 'چک ').replace(/\s+/g, ' ').trim();
}

/** دسته‌هایی که کالا یا فروش کالا هستند؛ مدتی که کنارشان آمده دورهٔ پوشش نیست. */
export const GOODS_CATEGORIES = Object.freeze(['مواد و کالا', 'بهای تمام‌شدهٔ فروش', 'ملزومات اداری', 'خوراک', 'فروش', 'کسری و ضایعات موجودی']);

/**
 * آیا متن سند یک خدمت دوره‌دار را نام می‌برد؟
 *
 * فقط نام خدمت، پس از کنار گذاشتن گارانتی و شرط پرداخت؛ مدتِ تنها کافی نیست.
 */
export function namesTimeBoundService(input) {
  return SERVICE_HEAD.test(withoutNonCoveragePeriods(input));
}
