/**
 * واژه‌های آوردهٔ سرمایه و دارایی ثابت — یک منبع، دو مصرف‌کننده.
 *
 * `voiceIntent` با این‌ها برگهٔ مخصوص باز می‌کند و `parser` با همین‌ها جلوی ثبت
 * خاموش را می‌گیرد. اگر هر کدام نسخهٔ خودش را داشت، از هم جدا می‌افتادند و
 * دقیقاً همان‌جا که برگه باز نمی‌شود، هشدار هم نبود.
 *
 * چرا اصلاً مهم است: آوردهٔ مالک درآمد نیست. اگر به‌عنوان درآمد ثبت شود، سود
 * دوره به اندازهٔ همان آورده باد می‌کند و مالیات روی پولی حساب می‌شود که خودِ
 * مالک گذاشته است. دارایی ثابت هم هزینهٔ دوره نیست.
 */

export const CAPITAL_PATTERNS = [
  /سرمایه\s*(?:را\s*)?(?:گذاشتم|گذاشتیم|آوردم|آوردیم|اضافه\s*کردم|اضافه\s*کردیم|واریز\s*کردم|ریختم)/,
  /افزایش\s*سرمایه/,
  /آورده\s*(?:نقدی|مالک|شریک)/,
  /سرمایه\s*اولیه/,
];

/**
 * تشخیص فقط با نشانهٔ صریح. حدس‌زدن از روی نام کالا («لپ‌تاپ خریدم») وسوسه‌انگیز
 * است ولی همان لپ‌تاپ می‌تواند کالای فروش یک مغازهٔ کامپیوتر باشد.
 */
export const FIXED_ASSET_PATTERNS = [/دارایی\s*ثابت/, /اموال\s*و\s*تجهیزات/, /خرید\s*سرمایه\s*ای/];

/** آیا جمله از آورده یا دارایی ثابت حرف می‌زند؟ ورودی باید نرمال‌شده باشد. */
export function mentionsCapitalOrAsset(normalizedText) {
  const text = String(normalizedText || '');
  if (CAPITAL_PATTERNS.some((pattern) => pattern.test(text))) return 'capital';
  if (FIXED_ASSET_PATTERNS.some((pattern) => pattern.test(text))) return 'fixed-asset';
  return null;
}
