/**
 * واژه‌های آوردهٔ سرمایه و دارایی ثابت — یک منبع، دو مصرف‌کننده.
 *
 * `voiceIntent` با این‌ها برگهٔ مخصوص باز می‌کند و `parser` با همین‌ها جلوی ثبت
 * خاموش را می‌گیرد. اگر هر کدام نسخهٔ خودش را داشت، از هم جدا می‌افتادند و
 * دقیقاً همان‌جا که برگه باز نمی‌شود، هشدار هم نبود.
 *
 * چرا اصلاً مهم است: آوردهٔ مالک درآمد نیست. اگر به‌عنوان درآمد ثبت شود، سود
 * دوره به اندازهٔ همان آورده باد می‌کند و مالیات روی پولی حساب می‌شود که خودِ
 * مالک گذاشته است. دارایی ثابت هم هزینهٔ دوره نیست.
 */

/**
 * «افزایش سرمایه»ای که آوردهٔ مالک نیست.
 *
 * - **سرمایهٔ بیمه:** «اضافه حق بیمه آتش سوزی بابت افزایش سرمایه ۲ میلیون دادیم»
 *   از مبلغ بیمه‌شده حرف می‌زند؛ حق بیمهٔ اضافه است که از شرکت بیرون رفته.
 *   بیمه، حق بیمه، بیمه‌نامه و الحاقیه هر جای جمله باشند، این واژه سرمایهٔ
 *   مالک نیست.
 * - **هزینهٔ افزایش سرمایه:** «هزینه ثبت افزایش سرمایه ۳ میلیون دادیم»،
 *   «حق الزحمه وکیل بابت افزایش سرمایه» — موضوع هزینه افزایش سرمایه است، ولی
 *   خودِ پول پرداخت شده، نه آورده.
 *
 * برگهٔ سرمایه فقط تأیید می‌گیرد و ورود وجه می‌زند؛ همین یک خطا پرداخت دو
 * میلیونی را دریافت دو میلیونی ثبت می‌کرد. جمله‌های بیرون‌مانده به پارسر و
 * موتور تصمیم می‌رسند: بیمه دورهٔ پوشش را می‌پرسد و هزینه هدف پرداخت را.
 * جهت فعل عمداً اینجا نیست: «افزایش سرمایه دادیم» می‌تواند واقعاً آورده باشد.
 */
const INSURED_SUM = 'بیمه|الحاقیه';
/**
 * کسی که کارِ افزایش سرمایه را انجام داده و پولش را گرفته — هر جای جمله.
 *
 * «۵ میلیون دادیم به وکیل بابت کارهای ثبتی افزایش سرمایه»، «۳ میلیون بابت ثبت
 * افزایش سرمایه به اداره ثبت دادیم»، «پول محضر برای افزایش سرمایه ۲ میلیون شد
 * دادیم»، «حسابرس برای گزارش افزایش سرمایه ۱۵ میلیون گرفت»: گیرندهٔ پول وکیل،
 * محضر، ادارهٔ ثبت یا حسابرس است؛ آوردهٔ مالک هرگز به این‌ها نمی‌رسد. فهرست
 * بسته‌ای از اسم‌های پیش از «افزایش سرمایه» (نسخهٔ قبلی) این جمله‌ها را از دست
 * می‌داد، چون گیرنده پیش یا پس از عبارت و با فاصلهٔ دلخواه می‌آید.
 */
const SERVICE_PROVIDER = '(?<![آ-ی])(?:وکیل|وکلا|محضر|دفترخانه|دفتر\\s*خانه|سردفتر|حسابرس|حسابرسی|کارشناس|کارشناسی|مشاور|اداره\\s*(?:ی\\s*)?ثبت|ثبت\\s*شرکت|ثبتی|روزنامه\\s*رسمی)';
// «بابت ثبت»، نه «ثبت» تنها: «ثبت افزایش سرمایه ۵۰۰ میلیون» فرمانِ ثبت است.
const COST_OF = '(?:هزینه|حق\\s*الزحمه|حق\\s*الوکاله|دستمزد|کارمزد|حق\\s*ثبت|(?:بابت|برای|هزینه)\\s*(?:ی\\s*)?ثبت|آگهی|روزنامه\\s*رسمی|تمبر|مالیات|عوارض|(?<![آ-ی])کار(?:ها|های|ای)?|(?<![آ-ی])گزارش)';
const OWNER_CAPITAL_INCREASE = new RegExp(`^(?![\\s\\S]*(?:${INSURED_SUM}|${SERVICE_PROVIDER}))[\\s\\S]*?(?<!${COST_OF}(?:\\s+\\S+){0,3}\\s*)افزایش\\s*سرمایه(?!\\s*(?:ه|ی)?\\s*(?:هزینه|کارمزد|حق\\s*الزحمه))`);

export const CAPITAL_PATTERNS = [
  /سرمایه\s*(?:را\s*)?(?:گذاشتم|گذاشتیم|آوردم|آوردیم|اضافه\s*کردم|اضافه\s*کردیم|واریز\s*کردم|ریختم)/,
  OWNER_CAPITAL_INCREASE,
  /آورده\s*(?:نقدی|مالک|شریک)/,
  // «آورده» واژهٔ حسابداری است، نه نام کالا؛ وقتی با فعلِ گذاشتن پول بیاید،
  // حتی با چند واژه فاصله، همان آورده است: «آورده به حساب کسب و کار گذاشتم».
  // نامتقارنی خطا این را توجیه می‌کند — هشدار اضافه یک کلیک است، ولی آوردهٔ
  // ثبت‌نشده یعنی سود دوره و مالیاتِ غلط. فعل لازم است تا «مشتری پول آورده»
  // که درآمد است، اینجا نیفتد.
  //
  // مثبت کاذبِ شناخته‌شده: «مشتری پول آورده و من گذاشتم توی صندوق». بستن این
  // یکی با ردکردن «و» در فاصله ممکن بود، ولی خودِ جملهٔ هدف «کسب و کار» دارد.
  // با همان استدلال بالا پذیرفته شده و عمداً باز مانده.
  /آورده(?:\s+\S+){0,6}\s*(?:گذاشتم|گذاشتیم|آوردم|آوردیم|ریختم|واریز\s*کردم)/,
  /سرمایه\s*اولیه/,
];

/**
 * تشخیص فقط با نشانهٔ صریح. حدس‌زدن از روی نام کالا («لپ‌تاپ خریدم») وسوسه‌انگیز
 * است ولی همان لپ‌تاپ می‌تواند کالای فروش یک مغازهٔ کامپیوتر باشد.
 */
export const FIXED_ASSET_PATTERNS = [/دارایی\s*ثابت/, /اموال\s*و\s*تجهیزات/, /خرید\s*سرمایه\s*ای/];

/** آیا جمله از آورده یا دارایی ثابت حرف می‌زند؟ ورودی باید نرمال‌شده باشد. */
export function mentionsCapitalOrAsset(normalizedText) {
  const text = String(normalizedText || '');
  if (CAPITAL_PATTERNS.some((pattern) => pattern.test(text))) return 'capital';
  if (FIXED_ASSET_PATTERNS.some((pattern) => pattern.test(text))) return 'fixed-asset';
  return null;
}
