/**
 * تنخواه در جمله — پرداختِ تنخواه یا خرج از آن.
 *
 * تا مهر ۱۴۰۵ «تنخواه» نامِ دیگرِ صندوق شمرده می‌شد: «ده میلیون از بانک به
 * تنخواه منتقل کردیم» انتقال به صندوق اصلی بود، «پنج میلیون تنخواه به رضایی
 * دادیم» سؤال «این پرداخت بابت چه بود؟» می‌گرفت که هیچ گزینه‌اش درست نبود، و
 * «از تنخواه پذیرایی خریدیم» از صندوق اصلی کم می‌شد. تنخواه پولِ شرکت است که
 * دست یک نفر است؛ نه صندوق اصلی است و نه هزینه.
 *
 * دو شکل از هم جدا می‌شوند:
 *
 * - **پرداخت تنخواه** (`fund`): پول از بانک یا صندوق به دارندهٔ تنخواه رفته —
 *   «تنخواه به رضایی دادیم»، «تنخواه رضایی رو شارژ کردیم»، «از ملت به تنخواه
 *   منتقل کردیم». هزینه نیست؛ انتقال است.
 * - **خرج از تنخواه** (`spend`): «از تنخواه پذیرایی خریدیم»، «رضایی از
 *   تنخواه کرایه داد». هزینه است، ولی از حساب تنخواه کم می‌شود نه از صندوق.
 *
 * الگوها روی متن خام اجرا می‌شوند؛ کنترل ارزان اول، چون تایپ زنده بودجهٔ
 * میلی‌ثانیه‌ای دارد.
 */
import { NUMBER_WORDS } from './counterpartySpeech.js';
import { normalizePersian } from './normalize.js';

const GAP = '[\\s\\u200c]*';
const TITLES = 'آقای|اقای|خانم|مهندس|دکتر|حاج|حاجی';

/** خرج از تنخواه: «از تنخواه»، «با تنخواه»، «از محل تنخواه». */
const SPEND = new RegExp(`(?:از|با)${GAP}(?:محل${GAP})?تنخواه`);
/** پرداخت یا شارژ تنخواه: فعل دادن و ریختن و شارژ، بی‌آنکه «از تنخواه» گفته شده باشد. */
const FUND_VERB = new RegExp([
  `(?:دادیم|دادم|داد(?![آ-ی])|دادن(?![آ-ی]))`,
  `(?:ریختیم|ریختم|ریخت(?![آ-ی]))`,
  `واریز${GAP}(?:کردیم|کردم|شد)`,
  `منتقل${GAP}(?:کردیم|کردم|شد)`, `انتقال${GAP}(?:دادیم|دادم)`,
  `شارژ${GAP}(?:کردیم|کردم|شد)`, `پر${GAP}(?:کردیم|کردم)`,
  `(?:گرفت|گرفتن)(?![آ-ی])`,
].join('|'));

const STOP = new Set(['گردان', 'گردانی', 'رو', 'را', 'به', 'برای', 'از', 'و', 'که', 'شرکت', 'دفتر', 'ما', 'مون',
  'دادیم', 'دادم', 'داد', 'ریختیم', 'شارژ', 'پر', 'واریز', 'منتقل', 'انتقال', 'گرفت', 'تومان', 'تومن', 'میلیون', 'هزار',
  'خرج', 'خرید', 'خریدیم', 'پرداخت', 'کردیم', 'کرد', 'شد', 'هم', 'این', 'اون', 'همون', 'دست', 'پیش']);

const clean = (word) => String(word || '').replace(/[،,.؛:!؟?]+$/, '').trim();

/**
 * دارندهٔ تنخواه از جمله، وقتی صریح گفته شده.
 *
 * «تنخواه رضایی»، «تنخواه آقای رضایی»، «تنخواه به خانم احمدی»، «به رضایی
 * تنخواه دادیم»، «رضایی از تنخواه…». نامِ حدسی بدتر از نبودِ نام است؛ هر جا
 * روشن نیست `null` برمی‌گردد و انتخاب حساب با ثبت‌کننده می‌ماند.
 *
 * در جملهٔ خرج، «به» گیرندهٔ پول را نشان می‌دهد نه دارنده را: در «از تنخواه به
 * آقای کریمی بابت تعمیر دادیم» کریمی تعمیرکار است.
 */
export function pettyCashHolder(input, { spend = false } = {}) {
  const text = normalizePersian(String(input || '')).replace(/‌/g, ' ');
  const patterns = [
    new RegExp(`تنخواه(?:\\s*گردان)?\\s+${spend ? '' : '(?:به\\s+)?'}(?:${TITLES})?\\s*([آ-ی]{2,})`),
    ...(spend ? [] : [
      // «تنخواه دادیم به کریمی»: فعل میان تنخواه و نام.
      new RegExp(`تنخواه(?:\\s*گردان)?\\s+(?:[^\\s]+\\s+){1,2}?به\\s+(?:${TITLES})?\\s*([آ-ی]{2,})`),
      new RegExp(`به\\s+(?:${TITLES})?\\s*([آ-ی]{2,})\\s+(?:[^\\s]+\\s+){0,4}?تنخواه`),
    ]),
    new RegExp(`(?:${TITLES})\\s+([آ-ی]{2,})\\s+(?:[^\\s]+\\s+){0,3}?(?:از\\s+)?تنخواه`),
    new RegExp(`([آ-ی]{3,})\\s+از\\s+تنخواه`),
  ];
  for (const pattern of patterns) {
    const name = clean(pattern.exec(text)?.[1]);
    // «از تنخواه دویست هزار…»: واژهٔ عددی نام نیست.
    if (name && !STOP.has(name) && !NUMBER_WORDS.has(name)) return name;
  }
  return null;
}

/** «تنخواه» در جمله چه نقشی دارد؟ `null` یعنی اصلاً از تنخواه حرفی نیست. */
export function readPettyCash(input) {
  const text = normalizePersian(String(input || ''));
  if (!text.includes('تنخواه')) return null;
  if (SPEND.test(text)) return { action: 'spend', holder: pettyCashHolder(text, { spend: true }) };
  if (FUND_VERB.test(text)) return { action: 'fund', holder: pettyCashHolder(text) };
  // «تنخواه» بی‌فعلِ روشن: خرج فرض نمی‌شود و پرداخت هم نه؛ ثبت‌کننده حساب را
  // روی برگه انتخاب می‌کند.
  return { action: 'unknown', holder: pettyCashHolder(text) };
}

/**
 * حساب تنخواهِ همین جمله، از میان حساب‌های دفتر.
 *
 * با نام دارنده، تنها تنخواهی که نامش را دارد؛ بی‌نام، فقط وقتی دفتر یک تنخواه
 * باز بیشتر ندارد. دو تنخواه و بی‌نام یعنی جمله روشن نیست و حدس زده نمی‌شود.
 */
export function pickPettyCashAccount(accounts = [], hint = null) {
  if (!hint) return null;
  const open = accounts.filter((account) => account.kind === 'petty' && account.active !== false && account.active !== 0);
  if (hint.holder) {
    const named = open.filter((account) => String(account.holderName || account.name || '').includes(hint.holder));
    return named.length === 1 ? named[0] : null;
  }
  return open.length === 1 ? open[0] : null;
}
