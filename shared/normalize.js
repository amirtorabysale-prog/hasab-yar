// یکسان‌سازی متن فارسی، جدا از پارسر.
//
// پارسر و ماژول تاریخ هر دو به این نیاز دارند؛ ماندنش داخل پارسر یک وابستگی
// حلقوی می‌ساخت و هر دو ماژول را از کار می‌انداخت.

const DIGITS = {
  '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4', '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9',
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
};

export function normalizePersian(input) {
  return String(input || '')
    .replace(/[۰-۹٠-٩]/g, (digit) => DIGITS[digit])
    .replace(/ي/g, 'ی').replace(/ك/g, 'ک')
    // غلط تایپی رایج واژهٔ مقیاس. «اجاره یکساله ۱۲۰ ملیون دادیم» صد و بیست
    // تومان ثبت می‌شد و کارت چک همان را فقط‌خواندنی نشان می‌داد: هر خوانندهٔ
    // مقیاس (پارسر، کارت چک، شاهد مبلغ در مسیر AI) شکل درست را می‌شناسد، پس
    // املا یک‌جا، همین‌جا، درست می‌شود. هیچ واژهٔ فارسی‌ای این دنباله را ندارد؛
    // «دوملیون» هم با همین درست می‌شود.
    .replace(/ملیون/g, 'میلیون').replace(/ملیارد/g, 'میلیارد')
    .replace(/(?<![آ-ی])میلون/g, 'میلیون')
    // کسرهٔ اضافه به شکل «هٔ» و «هٕ» در متن تایپی فارسی همه‌جا هست و بدون این
    // حذف، «اجارهٔ انبار» هرگز با قاعدهٔ «اجاره انبار» تطبیق نمی‌خورد.
    .replace(/[ٕٔ]/g, '')
    // همان کسرهٔ اضافه به شکل «ه‌ی» («بیمه‌ی آتش‌سوزی»، «اجاره‌ی انبار»). نیم‌فاصله
    // پایین‌تر فاصله می‌شود و «ی» تنها می‌ماند؛ پارسر آن را عدد «یک» می‌خواند و
    // کنار ۱۲ میلیون یک ردیف یک‌تومانی ثبت می‌شد، و دسته هم «بیمه» را گم می‌کرد.
    .replace(/([آ-ی])‌ی(?![آ-ی])/g, '$1')
    // «آ» عمداً دست‌نخورده می‌ماند: واژه‌نامه‌های جهت پول نرمال‌نشده‌اند و
    // یکسان‌سازی الف، «درآمد» را از تشخیص می‌انداخت.
    .replace(/ة/g, 'ه')
    .replace(/[‌ـ]/g, ' ')
    .replace(/٬/g, ',').replace(/٫/g, '.')
    .replace(/\s+/g, ' ').trim();
}
