import { normalizePersian } from './normalize.js';

/**
 * ماهیت یک پرداخت «بیمه»: لیست بیمهٔ حقوق (تأمین اجتماعی) یا حق بیمهٔ یک
 * بیمه‌نامه با دورهٔ پوشش.
 *
 * دو چیز کاملاً متفاوت با یک واژه:
 *
 * - **لیست بیمهٔ حقوق:** بدهی‌ای که لیست حقوق همان ماه ساخته؛ پرداختش تسویهٔ
 *   همان بدهی است و هزینهٔ تازه نیست.
 * - **حق بیمهٔ بیمه‌نامه:** تکمیلی، درمان، عمر، حوادث، مسئولیت، آتش‌سوزی…؛
 *   پولی که برای پوشش آینده رفته و پیش‌پرداخت است — حتی وقتی بیمه‌شده‌ها
 *   کارکنان یا کارگران‌اند.
 *
 * موتور تصمیم (`isTimeBoundService`) و دستیار بررسی حسابدار (`reviewNature`)
 * هر دو همین تابع را می‌خوانند. پیش از این دستیار هر جمله‌ای را که «بیمه» و
 * جایی «کارکنان»، «حقوق» (حتی «شخص حقوقی») یا «لیست» (حتی «لیست قیمت») داشت
 * لیست تأمین اجتماعی می‌خواند؛ موتور همان جمله را پیش‌پرداخت یک‌ساله تصمیم
 * گرفته بود و دستیار حسابدار را به صفحهٔ حقوق می‌فرستاد — یا بدتر، لیست باز
 * همان مبلغ را «پرداخت‌شده» می‌زد.
 *
 * قاعده:
 * - نشانهٔ صریح لیست (تأمین اجتماعی، لیست بیمه، بیمهٔ بیکاری، سهم کارفرما و
 *   کارگر، لیست حقوق در کنار بیمه) همیشه لیست است.
 * - «بیمه» چسبیده به پرسنل/کارگر/کارکنان لیست است، مگر جمله نشانهٔ حق بیمه
 *   داشته باشد: رشتهٔ بیمه پس از «بیمه»، «بیمه‌نامه»، یا طول و دورهٔ پوشش.
 * - خسارت و غرامت دریافت از بیمه‌گر است؛ نه حق بیمه و نه لیست.
 */
const STAFF = '(?:پرسنل|کارگر|کارگران|کارکنان|کارمند|کارمندان|نیروها|کارگرها|کارمندها)';
const STATUTORY = /ت[اأ]مین اجتماع|لیست بیمه|بیمه(?: ?ی)? بیکاری|سهم (?:کارفرما|کارگر|کارگران|کارمند|کارمندان|کارکنان|بیمه شده)/;
const STAFF_ADJACENT = new RegExp(`بیمه(?: ?ی)? ${STAFF}(?![آ-ی])`);
const PAYROLL_LIST = /لیست (?:حقوق|دستمزد)/;
const PREMIUM_LINE = /بیمه(?: ?ی)? ?(?:نامه|تکمیلی|درمان|درمانی|عمر|حوادث|حادثه|مسئولیت|مسیولیت|مسولیت|اتش|آتش|بدنه|شخص ثالث|ثالث|انبار|سرقت|باربری|محموله|اموال|تجهیزات|ماشین|خودرو|دستگاه|کارگاه|ساختمان|مغازه|دفتر|زلزله|سیل|مهندسی|اعتبار|سایبری)/;
const COVERAGE = /(?:یک|دو|سه|[0-9]+) ?ساله|یکساله|(?:یک|دو|سه|چهار|پنج|شش|هفت|هشت|نه|ده|یازده|دوازده|[0-9]+) ?ماهه|سالانه|پوشش|از (?:اول |ابتدای )?(?:فروردین|اردیبهشت|خرداد|تیر|مرداد|شهریور|مهر|آبان|آذر|دی|بهمن|اسفند)[^.،]{0,24} تا /;
const CLAIM = /خسارت|غرامت/;
// فعل‌های پرداخت، رسمی و محاوره؛ «پس داد» و «برگشت» پرداخت ما نیستند.
const PAID = /پرداخت|تسویه|واریز|ریختیم|ریختم|ریخت(?![آ-ی])|زدیم|زدم|کارت به کارت|حواله|فرستادیم|فرستادم|دادیم|دادم|دادن(?![آ-ی])|داد(?![آ-ی])|دادند/;

export function insuranceNature(text) {
  const t = normalizePersian(String(text || '')).replace(/\s+/g, ' ');
  const insurance = /بیمه/.test(t);
  if (!insurance) return { insurance, statutory: false, staffPayroll: false, premium: false, coverage: false, claim: false, payrollList: false, paid: PAID.test(t) };
  const statutory = STATUTORY.test(t) || PAYROLL_LIST.test(t);
  const staffPayroll = STAFF_ADJACENT.test(t);
  const coverage = COVERAGE.test(t);
  const premium = PREMIUM_LINE.test(t) || coverage;
  const claim = CLAIM.test(t);
  // لیست بیمهٔ حقوق: نشانهٔ صریح، یا «بیمهٔ کارکنان» بی‌هیچ نشانهٔ بیمه‌نامه.
  const payrollList = statutory || (staffPayroll && !premium && !claim);
  return { insurance, statutory, staffPayroll, premium, coverage, claim, payrollList, paid: PAID.test(t) };
}

/** پرداخت لیست بیمهٔ حقوق — تسویهٔ بدهی لیست، نه هزینه و نه پیش‌پرداخت. */
export function isPayrollInsurancePayment(text) {
  const nature = insuranceNature(text);
  return nature.payrollList && nature.paid;
}

/**
 * «بیمه»ای که حق بیمهٔ دوره‌دار نیست: لیست حقوق یا خسارت. همان شرطی که موتور
 * برای دستهٔ «بیمه» پیش از پیش‌پرداخت دانستنش می‌پرسد.
 */
export function isNotInsurancePremium(text) {
  const nature = insuranceNature(text);
  return nature.payrollList || nature.claim;
}
