import { normalizePersian } from './normalize.js';
import { detectPartnerFundedSpend } from './partnerPaidSpeech.js';

/**
 * هدف خرید — تفاوت هزینه، موجودی و دارایی ثابت.
 *
 * «لپ‌تاپ ۴۵ میلیون خریدم» از روی خودِ جمله هیچ‌کدام از سه نیست: برای یک
 * دفتر مهندسی دارایی ثابت است، برای یک مغازهٔ کامپیوتر کالای فروش. حدس زدنش
 * از روی نام کالا همان چیزی است که `capitalSpeech` عمداً نکرده. جوابش یک
 * سؤال است، و این فایل می‌گوید کِی آن سؤال لازم است و کِی نیست.
 */

/**
 * دسته‌هایی که ذاتاً مصرف همان دوره‌اند.
 *
 * قبض، غذا، کرایه، سوخت، کارمزد بانک، تبلیغ و آموزش هیچ‌وقت موجودی یا دارایی
 * ثابت نمی‌شوند. پرسیدن «این خرید برای چیست؟» از آن‌ها فقط اصطکاک است، و
 * بی‌پاسخ گذاشتنشان یعنی با روشن شدن موتور، ساده‌ترین هزینه‌ها هم به صف حسابدار
 * می‌رفتند.
 *
 * اجاره، بیمه و اشتراک اینجا نیستند: دوره‌دارند و سیاست پیش‌پرداخت خودشان را
 * دارند. تعمیر هم نیست — تعمیر اساسی مخارج سرمایه‌ای است و قضاوت می‌خواهد.
 */
export const ROUTINE_EXPENSE_CATEGORIES = Object.freeze([
  'قبوض', 'خوراک', 'حمل‌ونقل', 'سوخت و ایاب‌وذهاب', 'کارمزد بانکی', 'تبلیغات و بازاریابی', 'آموزش',
]);

/**
 * دسته‌هایی که پشتشان ممکن است کالا باشد — مصرفی، فروشی یا ماندگار.
 *
 * «ملزومات اداری» هم خودکار و کاغذ را می‌گیرد و هم پرینتر را؛ «سایر هزینه‌ها»
 * یعنی دسته‌بند واژهٔ آشنایی پیدا نکرد، که برای لپ‌تاپ و میز و یخچال دقیقاً
 * همین اتفاق می‌افتد.
 */
const GOODS_CATEGORIES = Object.freeze(['ملزومات اداری', 'مواد و کالا', 'سایر هزینه‌ها']);

/** ملزوماتی که زیر حد سرمایه‌ای شدن‌اند، بی‌سؤال مصرف جاری‌اند. */
const PRESUMED_CONSUMABLE = 'ملزومات اداری';

// «خرید» در همهٔ صورت‌هایش: خریدم، خریدیم، خریداری، خرید کردیم.
const PURCHASE_VERB = /خرید/;

const RESALE = /(?:برای|واسه|واسه\s*ی|جهت)\s*(?:فروش|فروختن|فروش\s*مجدد)|برای\s*مغازه\s*که\s*بفروشیم/;
const PRODUCTION = /(?:برای|واسه|جهت)\s*(?:تولید|خط\s*تولید|ساخت)|مواد\s*اولیه/;

const text = (facts) => normalizePersian(String(facts?.utterance || facts?.evidence || ''));
const category = (facts) => String(facts?.category || '').trim();

/**
 * نشانه‌هایی که می‌گویند این پرداخت ساده نیست، هرچه دسته‌اش باشد.
 *
 * هر کدام از یک سناریوی واقعی آمده‌اند: کرایهٔ حملِ محمولهٔ وارداتی جزو بهای
 * کالاست نه هزینهٔ حمل؛ «نمی‌دانم فاکتورش ثبت شده یا بدهی قبلی بود» تسویه است
 * نه خرید؛ «خرید وسایل ویلای شخصی شریک» برداشت مالک است؛ و «چطور ثبت کنیم؟» با
 * فاکتور غیررسمی، سؤال مالیاتی است. هیچ‌کدام با برچسب «هزینه» یا با سؤال
 * هدف خرید درست نمی‌شوند — جایشان صف حسابدار است.
 */
const NEEDS_JUDGMENT = /[?؟]|نمی\s*دونم|نمی\s*دانم|چطور|چگونه|شخصی|شریک|سهامدار|ارزش\s*افزوده|مالیات|غیر\s*رسمی|بدهی\s*قبلی|طلب\s*قبلی|محموله|واردات|وارداتی|گمرک|ترخیص|بارنامه|انبار/;

/**
 * منبع پولی که گفته شده، قضاوت نیست.
 *
 * «شریکمون هزینه تعمیر کولر رو از جیب خودش داد» پرداخت‌کننده و جهت را گفته:
 * شرکت به شریک بدهکار شد. همان جمله با «مدیرعامل» سؤال هدف را می‌گرفت و با
 * «شریک» به صف حسابدار می‌رفت. فقط واژه‌های پرداخت‌کننده کنار می‌روند؛
 * «وسایل ویلای شخصی شریک» (مصرف شخصی) هنوز «شخصی» دارد و قضاوت می‌ماند.
 */
const FUNDER_WORDS = /(?:(?:از|با)\s*)?(?:پول|جیب|حساب|کارت)\s*(?:شخصی|خودش|خودشون|خودشان|خودم|خودمون)(?:\s*(?:ش|اش|خودش|خودشون))?(?![آ-ی])|(?:شریک|سهام\s*دار)[آ-ی]*/g;

/** آیا گفته نشانه‌ای دارد که ساده دیدنش را ناامن می‌کند؟ */
export function needsJudgment(facts) {
  const value = text(facts);
  return NEEDS_JUDGMENT.test(detectPartnerFundedSpend(value) ? value.replace(FUNDER_WORDS, ' ') : value);
}

/**
 * هدفی که خودِ کاربر در جمله گفته — فقط وقتی صریح است.
 *
 * «جنس خریدم برای فروش» جواب سؤال را از پیش داده؛ پرسیدن دوباره‌اش یعنی
 * سیستم حرف کاربر را نشنیده. «برای دفتر» یا «برای گرافیست» عمداً اینجا نیست:
 * دفتر هم کاغذ مصرف می‌کند و هم میز نگه می‌دارد.
 */
export function purchasePurposeFromSpeech(sentence) {
  const value = normalizePersian(String(sentence || ''));
  if (RESALE.test(value)) return 'resale';
  if (PRODUCTION.test(value)) return 'production';
  return null;
}

/** پرداخت سادهٔ همین دوره، بی‌آنکه سؤالی لازم باشد؟ */
export function isRoutineExpense(facts, { capitalizationThreshold = null } = {}) {
  if (needsJudgment(facts)) return false;
  if (ROUTINE_EXPENSE_CATEGORIES.includes(category(facts))) return true;
  // ملزومات زیر حد سرمایه‌ای شدنِ خودِ دفتر، حتی اگر ماندگار باشند، هزینه‌اند.
  // بدون حد، پرینتر و خودکار از هم جدا نمی‌شوند و سؤال پرسیده می‌شود.
  // تعمیر هم همین‌طور: تعمیر اساسیِ سرمایه‌ای بالای حد است؛ تعمیر کولر چهار
  // میلیونی زیر حد، هزینهٔ همین دوره است و پرسیدن «بابت چه بود» فقط اصطکاک.
  return [PRESUMED_CONSUMABLE, 'تعمیر و نگهداری'].includes(category(facts))
    && Number.isSafeInteger(capitalizationThreshold) && Number(facts?.amount) < capitalizationThreshold;
}

/** خرید کالایی که هدفش معلوم نیست، پس باید پرسید. */
export function needsPurchasePurpose(facts, context = {}) {
  if (facts?.intendedUse) return false;
  if (isRoutineExpense(facts, context)) return false;
  if (!GOODS_CATEGORIES.includes(category(facts))) return false;
  // پول به شخص نام‌برده ممکن است تسویهٔ بدهی یا پیش‌پرداخت باشد، نه خرید تازه.
  if (needsJudgment(facts) || facts?.counterparty) return false;
  // «ده میلیون دادم» بدون فعل خرید، اصلاً معلوم نیست خرید بوده؛ پرسیدن هدفِ
  // خرید از آن سؤال غلط است و جایش همان صف حسابدار است.
  return category(facts) !== 'سایر هزینه‌ها' || PURCHASE_VERB.test(text(facts));
}
