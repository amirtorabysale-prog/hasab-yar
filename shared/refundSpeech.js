/**
 * برگشت وجه یا فسخ قرارداد دوره‌دار — یک منبع برای هر مسیری که جمله را می‌خواند.
 *
 * «بیمه آتش‌سوزی رو فسخ کردیم، بیمه دی ۶ میلیون حق بیمه برگشت داد به حساب
 * تجارت» پرداخت تازه خوانده می‌شد: پارسر نوع را «هزینه» و دسته را «بیمه»
 * می‌گذاشت، سیاست پیش‌پرداخت دورهٔ پوشش را می‌پرسید و هر جوابی پول را از بانک
 * بیرون می‌برد — بانک ۱۲ میلیون جابه‌جا می‌شد و بیمه‌ای که ۶ میلیونش برگشته بود
 * ۱۸ میلیون هزینه می‌ساخت. آینه‌اش هم بود: «مشتری اشتراک یک‌ساله رو کنسل کرد،
 * ۶ میلیون بهش برگشت زدیم» پیش‌پرداخت اشتراکِ خودمان با برنامهٔ دوازده‌ماهه ثبت
 * می‌شد.
 *
 * برگشت وجه، پیش‌پرداخت، ودیعه یا پیش‌دریافتِ قبلی را کم می‌کند و برنامهٔ
 * شناسایی باقی‌مانده را می‌بندد؛ کدام قرارداد، از متن درنمی‌آید. پس جمله به
 * حسابدار می‌رود (قاعدهٔ ۴ CLAUDE.md) — هرگز پیش‌پرداخت تازه، هزینه یا ودیعهٔ تازه.
 *
 * شکل‌ها: «برگشت داد/زدن/خورد/شد»، «برگشتی»، «ریفاند»، «پس گرفتیم»، «پس داد/
 * برگردوند»، «عودت شد/کرد»، «مسترد شد»، و «فسخ/کنسل/لغو» کنار مبلغ. «پس می‌گیریم» (آینده، شرطِ
 * ودیعه) و «قابل استرداد» برگشت نیستند؛ «چک برگشت خورد» برگشت چک است و مسیر
 * خودش را دارد؛ «رفت و برگشت» کرایهٔ مسیر است؛ «لغو نکردیم/فسخ نشد» فسخ نیست.
 *
 * دو پرسش جدا: آیا جمله قضاوت حسابدار می‌خواهد (`readContractRefund` — برگشت یا
 * فسخِ کنار مبلغ)، و جهت پول (`contractRefundDirection`) که فقط از فعل صریح
 * خوانده می‌شود. «جریمهٔ فسخ اجاره ۵ میلیون دادیم» فسخ است ولی پولِ رفته؛
 * «مستاجر قرارداد رو فسخ کرد و ۱۰ میلیون خسارت داد» پولِ آمده. فسخ تنها جهتی
 * نمی‌سازد؛ جهت همان فعل خود جمله است.
 */
import { normalizePersian } from './normalize.js';

const GAP = '[\\s‌]*';
const END = '(?![آ-ی])';
const MONEY = '(?:\\d|میلیون|هزار|میلیارد|تومان|تومن|ریال)';
// «رفت و برگشت» مسیرِ کرایه است، نه پولِ برگشتی.
const NOT_ROUND_TRIP = '(?<![آ-ی])(?<!رفت[\\s‌]*و[\\s‌]*)';
/** فعل یا واژهٔ صریحِ برگشتِ پول. */
const RETURN_WORD = new RegExp([
  `${NOT_ROUND_TRIP}برگشت${GAP}(?:داد|زد|خورد|شد|کرد)(?:یم|م|ن|ند|ه)?${END}`,
  `${NOT_ROUND_TRIP}برگشت${GAP}داده${GAP}شد${END}`,
  `${NOT_ROUND_TRIP}برگشت(?:ی|ی${GAP}ها)${END}`,
  `(?<![آ-ی])(?:پول|پولش|پولمون|وجه|وجهش)${GAP}(?:\\S+${GAP}){0,3}?برگشت${END}`,
  'ریفاند|refund',
  `(?<![آ-ی])پس${GAP}گرفت(?:یم|م|ن|ند|ه)?${END}`,
  // «صاحبخونه ودیعه رو پس داد/برگردوند» و آینه‌اش «ودیعهٔ مستاجر رو پس دادیم».
  `(?<![آ-ی])پس${GAP}داد(?:ن|ند|یم|م)?${END}`,
  `(?<![آ-ی])برگر(?:دو|دا)ند(?:ن|ند|یم|م)?${END}`,
  `(?<![آ-ی])(?:عودت|مسترد|استرداد)${GAP}(?:شد|گردید|کرد(?:ن|ند)?|داد(?:ن|ند)?)${END}`,
].join('|'), 'i');
// فسخ یا لغوِ کنار مبلغ — نه منفی‌اش («لغو نکردیم»، «فسخ نشد»).
const NOT_NEGATED = `(?!${GAP}ن(?:کرد|شد|شده|می)[آ-ی]*)`;
const CANCELLATION = new RegExp([
  `(?<![آ-ی])(?:فسخ|کنسل|لغو)(?:ی)?${END}${NOT_NEGATED}(?:${GAP}\\S+){0,8}?${GAP}${MONEY}`,
  `${MONEY}(?:${GAP}\\S+){0,8}?${GAP}(?:فسخ|کنسل|لغو)${END}${NOT_NEGATED}`,
].join('|'));
// برگشت چک، وصول‌نشدن چک است، نه برگشت وجه قرارداد.
const BOUNCED_CHEQUE = /(?<![آ-ی])چک(?:\s+\S+){0,4}?\s+برگشت/;
// موضوعِ قراردادِ دوره‌دار یا ودیعه. «جنس برگشتی رو پس دادیم» برگشت کالاست و
// قاعدهٔ برگشت از خرید/فروش (moneyPurpose) آن را می‌گیرد، نه این.
const CONTRACT_SUBJECT = /(?<![آ-ی])(?:بیمه|بیمع|اجاره|کرایه|اشتراک|لایسنس|ودیعه|رهن|قرارداد|پشتیبانی|نرم\s*افزار|هاست|دامنه|آنتی\s*ویروس|انتی\s*ویروس|عضویت|شهریه)/;

function contractText(input) {
  const text = normalizePersian(input);
  if (!text || BOUNCED_CHEQUE.test(text) || !CONTRACT_SUBJECT.test(text)) return null;
  return text;
}

/** آیا جمله از برگشت وجه یا فسخ قرارداد دوره‌دار یا ودیعه می‌گوید؟ (قضاوت حسابدار) */
export function readContractRefund(input) {
  const text = contractText(input);
  return Boolean(text) && (RETURN_WORD.test(text) || CANCELLATION.test(text));
}

export const CONTRACT_REFUND_REASON = 'برگشت وجه یا فسخ قرارداد، پیش‌پرداخت، ودیعه یا پیش‌دریافت قبلی را کم می‌کند؛ پرداخت یا دریافت تازه نیست و حسابدار آن را با قرارداد اصلی تطبیق می‌دهد.';

/**
 * جهت پولِ برگشتی، فقط از فعل صریح.
 *
 * - برگشت یا پس‌دادنِ اول‌شخص («بهش برگشت زدیم»، «ودیعه رو پس دادیم») — خروج؛
 * - دریافتِ اول‌شخص («پس گرفتیم»، «دریافت کردیم») — ورود؛
 * - فعلِ پرداختِ سوم‌شخص («بیمه برگشت داد»، «واریز کرد»، «خسارت داد») — ورود،
 *   مگر گیرنده کس دیگری باشد؛
 * - برگشتِ مجهول («عودت شد»، «ریفاند شد»، «برگشت خورد») — به مشتری یا مستاجر
 *   خروج، وگرنه ورود.
 *
 * فعلِ پرداختِ اول‌شخص («جریمهٔ فسخ رو دادیم») یا فسخِ بی‌فعلِ برگشت جهتی
 * نمی‌سازد (`null`): جهت همان است که خودِ جمله گفته. `subject` متنِ کل جمله است
 * وقتی `input` فقط بندِ یک ردیف است.
 */
const REFUND_BY_US = /(?<![آ-ی])(?:(?:برگشت|پس|عودت)\s*(?:زدیم|دادیم|کردیم|زدم|دادم|کردم)|برگر(?:دو|دا)ند(?:یم|م))(?![آ-ی])/;
const RECEIVED_BY_US = /(?<![آ-ی])(?:پس\s*گرفت(?:یم|م)|(?:دریافت|وصول)\s*کرد(?:یم|م)|گرفت(?:یم|م))(?![آ-ی])/;
const PAID_BY_US = /(?<![آ-ی])(?:دادیم|دادم|ریختیم|ریختم|زدیم|زدم|پرداخت\s*(?:کردیم|کردم)|واریز\s*(?:کردیم|کردم)|کارت\s*به\s*کارت\s*(?:کردیم|کردم))(?![آ-ی])/;
const PAID_BY_THEM = /(?<![آ-ی])(?:برگشت\s*(?:داد|دادن|دادند|زد|زدن|زدند)|پس\s*(?:داد|دادن|دادند)|برگر(?:دو|دا)ند(?:ن|ند)?|(?:عودت|مسترد)\s*(?:کرد|کردن|کردند|داد|دادن|دادند)|داد|دادن|دادند|ریخت|ریختن|(?:واریز|پرداخت|کارت\s*به\s*کارت|تسویه)\s*(?:کرد|کردن|کردند))(?![آ-ی])/;
const PASSIVE_RETURN = /(?<![آ-ی])(?<!رفت\s*و\s*)(?:برگشت\s*(?:شد|خورد|داده\s*شد)|(?:عودت|مسترد|استرداد)\s*(?:شد|گردید)|ریفاند|refund|برگشتی|(?:پول|پولش|پولمون|وجه|وجهش)\s*(?:\S+\s*){0,3}?برگشت(?![آ-ی]))/i;
const TO_US = /(?<![آ-ی])(?:به\s*حساب(?:مون|\s*ما|\s*شرکت)?|به\s*کارت|بهمون|به\s*ما)(?![آ-ی])/;
const CUSTOMER_SIDE = /(?<![آ-ی])(?:مشتری|مست[اأ]جر|خریدار|کارفرما)(?:\s*(?:مون|مان|ش|شون))?(?![آ-ی])|(?<![آ-ی])(?:بهش|براش|بهشون|براشون)(?![آ-ی])/;
const TO_OTHER = /(?<![آ-ی])(?:بهش|براش|بهشون|براشون|به\s*(?:مشتری|مست[اأ]جر|خریدار|آقای|اقای|خانم))(?![آ-ی])/;
export function contractRefundDirection(input, { subject = input } = {}) {
  if (!readContractRefund(subject)) return null;
  const text = normalizePersian(input);
  if (REFUND_BY_US.test(text)) return 'out';
  if (RECEIVED_BY_US.test(text)) return 'in';
  if (PAID_BY_US.test(text)) return null;
  if (PAID_BY_THEM.test(text)) return TO_OTHER.test(text) && !TO_US.test(text) ? 'out' : 'in';
  if (PASSIVE_RETURN.test(text)) return CUSTOMER_SIDE.test(text) && !TO_US.test(text) ? 'out' : 'in';
  return null;
}
