import { normalizePersian } from './normalize.js';

/**
 * «پول برگشت» — فقط وقتی واقعاً برگشته است.
 *
 * دستیار حسابدار جهت نقد را با این گفته وارونه می‌پذیرد (ورود وجه که
 * پیش‌پرداخت یا ودیعه را کم می‌کند، خروج وجه که پیش‌دریافت را کم می‌کند) و
 * جهت پرداخت اولیه را رد می‌کند. پس هر وعده، شرط یا مجهولِ آینده که این‌جا
 * «برگشت» خوانده شود، پرداخت درست ودیعه یا دریافت درست اجارهٔ جلو را قفل
 * می‌کند:
 *
 * - «ودیعه … دادیم که موقع تخلیه پس داده میشه» — وعده است، پولی برنگشته.
 * - «آخر قرارداد برگردونده میشه»، «اگه زودتر بره عودت داده میشه» — شرط.
 * - «از حقوقش پس گرفته میشه» — کسر آینده، نه دریافت.
 * - «هنوز پس داده نشده» — نفی.
 *
 * و در لیست بیمه: «تأمین اجتماعی … بهمون پس داد» پول آمده است؛ «داد» آن
 * پرداخت ما نیست.
 *
 * فعل گذشته یا ماضی نقلی («پس داد»، «پس دادیم»، «پس داده»، «پس داده شد»،
 * «عودت شد»، «مسترد شد»، «برگردوند»، «برگردونده»، «برگشت زدن») برگشت است؛
 * همان فعل با «میشه/می‌شود/بشه/شود/خواهد/نشد/نشده» پس از آن، نه.
 */
const AFTER = '(?![آ-ی])(?! ?(?:می ?شه|می ?شود|می ?شن|می ?شوند|بشه|بشود|بشن|بشوند|شه|شود|شوند|خواهد|خواهند|نشد|نشده|نشدن|نشه|نشود|نمی ?شه|نمی ?شود)(?![آ-ی]))';
const PAST_RETURN = new RegExp([
  `پس (?:داد|دادن|دادند|دادیم|دادم|دادی|داده|گرفت|گرفتن|گرفتند|گرفتیم|گرفتم|گرفته)(?:ش|شون|شان)?${AFTER}`,
  `عودت (?:داد|دادن|دادند|دادیم|دادم|داده|شد|شده|کرد|کردن|کردند|کردیم|کردم|کرده|گردید)${AFTER}`,
  `(?<!قابل )(?:مسترد|استرداد) (?:شد|شده|کرد|کردن|کردند|کردیم|کرده|گردید)${AFTER}`,
  `برگرد[وا]ند(?:ه|ن|ند|یم|م|ید|ین)?(?:ش|شون|شان)?${AFTER}`,
  `برگشت (?:داد|دادن|دادند|دادیم|داده|زد|زدن|زدند|زدیم)${AFTER}`,
  `بازپرداخت (?:شد|شده|کرد|کردن|کردند|کردیم)${AFTER}`,
].join('|'));

/** واژهٔ برگشت بی‌فعل گذشته («عودت پیش‌دریافت …»، «بازپرداخت …») — عنوانِ سند، نه وعده. */
const RETURN_NOUN = /(?<![آ-ی])(?:عودت|بازپرداخت)(?![آ-ی])/;
/** وعده، شرط یا نفیِ برگشت: «پس میده»، «پس بدیم»، «عودت داده میشه»، «برمیگرده»، «قابل استرداد». */
const RETURN_PROMISED = new RegExp([
  'پس (?:می ?د|بد|نمی ?د|ند|نمی ?گیر|می ?گیر|بگیر)',
  'عودت (?:می ?د|بد|می ?ش|می ?کن|بکن|نمی)',
  'بر ?می ?گرد|بر ?نمی ?گرد',
  'قابل (?:استرداد|برگشت|عودت)',
  '(?:شرط|صورت|امکان|حق|موقع|زمان) (?:عودت|بازپرداخت|استرداد|برگشت)',
  `(?:پس|عودت|برگشت|مسترد|استرداد|بازپرداخت|برگرد[وا]ند[هن]?) ?(?:داده |گرفته |کرده )?(?:می ?شه|می ?شود|می ?شن|بشه|بشود|شود|خواهد|نشد|نشده|نشه|نشود|نمی ?شه|نمی ?شود)(?![آ-ی])`,
].join('|'));

/** پولی که واقعاً برگشت (فعل گذشته)؛ وعده، شرط و نفی نه. */
export function moneyReturned(text) {
  return PAST_RETURN.test(normalizePersian(String(text || '')).replace(/\s+/g, ' '));
}

/** برگشت با فعل گذشته، یا عنوان سند برگشت («عودت ودیعه …») بی هیچ وعده و شرطی. */
export function returnRecorded(text) {
  const t = normalizePersian(String(text || '')).replace(/\s+/g, ' ');
  return PAST_RETURN.test(t) || (RETURN_NOUN.test(t) && !RETURN_PROMISED.test(t));
}
