/**
 * برگشت وجه یا فسخ قرارداد دوره‌دار — یک منبع برای هر مسیری که جمله را می‌خواند.
 *
 * «بیمه آتش‌سوزی رو فسخ کردیم، بیمه دی ۶ میلیون حق بیمه برگشت داد به حساب
 * تجارت» پرداخت تازه خوانده می‌شد: پارسر نوع را «هزینه» و دسته را «بیمه»
 * می‌گذاشت، سیاست پیش‌پرداخت دورهٔ پوشش را می‌پرسید و هر جوابی پول را از بانک
 * بیرون می‌برد — بانک ۱۲ میلیون جابه‌جا می‌شد و بیمه‌ای که ۶ میلیونش برگشته بود
 * ۱۸ میلیون هزینه می‌ساخت. آینه‌اش هم بود: «مشتری اشتراک یک‌ساله رو کنسل کرد،
 * ۶ میلیون بهش برگشت زدیم» پیش‌پرداخت اشتراکِ خودمان با برنامهٔ دوازده‌ماهه ثبت
 * می‌شد.
 *
 * برگشت وجه، پیش‌پرداخت، ودیعه یا پیش‌دریافتِ قبلی را کم می‌کند و برنامهٔ
 * شناسایی باقی‌مانده را می‌بندد؛ کدام قرارداد، از متن درنمی‌آید. پس جمله به
 * حسابدار می‌رود (قاعدهٔ ۴ CLAUDE.md) — هرگز پیش‌پرداخت تازه، هزینه یا ودیعهٔ تازه.
 *
 * شکل‌ها: «برگشت داد/زدن/خورد/شد»، «برگشتی»، «ریفاند»، «پس گرفتیم»، «عودت
 * شد/کرد»، «مسترد شد»، و «فسخ/کنسل/لغو» کنار مبلغ. «پس می‌گیریم» (آینده، شرطِ
 * ودیعه) و «قابل استرداد» برگشت نیستند؛ «چک برگشت خورد» برگشت چک است و مسیر
 * خودش را دارد.
 */
import { normalizePersian } from './normalize.js';

const GAP = '[\\s‌]*';
const END = '(?![آ-ی])';
const MONEY = '(?:\\d|میلیون|هزار|میلیارد|تومان|تومن|ریال)';
const CONTRACT_REFUND = new RegExp([
  `(?<![آ-ی])برگشت${GAP}(?:داد|زد|خورد|شد|کرد)(?:یم|م|ن|ند|ه)?${END}`,
  `(?<![آ-ی])برگشت(?:ی|ی${GAP}ها)${END}`,
  `(?<![آ-ی])پولش${GAP}(?:\\S+${GAP}){0,3}?برگشت${END}`,
  'ریفاند|refund',
  `(?<![آ-ی])پس${GAP}گرفت(?:یم|م|ن|ند|ه)?${END}`,
  `(?<![آ-ی])(?:عودت|مسترد|استرداد)${GAP}(?:شد|گردید|کرد(?:ن|ند)?|داد(?:ن|ند)?)${END}`,
  `(?<![آ-ی])(?:فسخ|کنسل|لغو)(?:ی)?${END}(?:${GAP}\\S+){0,8}?${GAP}${MONEY}`,
  `${MONEY}(?:${GAP}\\S+){0,8}?${GAP}(?:فسخ|کنسل|لغو)${END}`,
].join('|'), 'i');
// برگشت چک، وصول‌نشدن چک است، نه برگشت وجه قرارداد.
const BOUNCED_CHEQUE = /(?<![آ-ی])چک(?:\s+\S+){0,4}?\s+برگشت/;
// موضوعِ قراردادِ دوره‌دار یا ودیعه. «جنس برگشتی رو پس دادیم» برگشت کالاست و
// قاعدهٔ برگشت از خرید/فروش (moneyPurpose) آن را می‌گیرد، نه این.
const CONTRACT_SUBJECT = /(?<![آ-ی])(?:بیمه|بیمع|اجاره|کرایه|اشتراک|لایسنس|ودیعه|رهن|قرارداد|پشتیبانی|نرم\s*افزار|هاست|دامنه|آنتی\s*ویروس|انتی\s*ویروس|عضویت|شهریه)/;

/** آیا جمله از برگشت وجه یا فسخ قرارداد دوره‌دار یا ودیعه می‌گوید؟ */
export function readContractRefund(input) {
  const text = normalizePersian(input);
  if (!text || BOUNCED_CHEQUE.test(text) || !CONTRACT_SUBJECT.test(text)) return false;
  return CONTRACT_REFUND.test(text);
}

export const CONTRACT_REFUND_REASON = 'برگشت وجه یا فسخ قرارداد، پیش‌پرداخت، ودیعه یا پیش‌دریافت قبلی را کم می‌کند؛ پرداخت یا دریافت تازه نیست و حسابدار آن را با قرارداد اصلی تطبیق می‌دهد.';

/**
 * جهت پولِ برگشتی.
 *
 * برگشت به ما (بیمه‌گر، فروشندهٔ نرم‌افزار، موجر پول را پس داد) ورود پول است؛
 * برگشت به مشتری یا مستاجر («بهش برگشت زدیم»، «پس دادیم»، «وجه اشتراک مشتری
 * عودت شد») خروج پول است. `null` یعنی جمله برگشت نیست.
 */
const REFUND_BY_US = /(?<![آ-ی])(?:برگشت|پس|عودت)\s*(?:زدیم|دادیم|کردیم|زدم|دادم|کردم)(?![آ-ی])/;
const CUSTOMER_SIDE = /(?<![آ-ی])(?:مشتری|مست[اأ]جر|خریدار|کارفرما)(?:\s*(?:مون|مان|ش|شون))?(?![آ-ی])|(?<![آ-ی])(?:بهش|براش|بهشون|براشون)(?![آ-ی])/;
const TO_US = /(?<![آ-ی])پس\s*گرفت(?:یم|م)|به\s*حساب(?:مون|\s*ما|\s*شرکت)?|به\s*کارت|ریفاند|refund|برگشت\s*(?:داد|زدن|زدند|خورد)|دریافت\s*کرد(?:یم|م)|واریز\s*کرد(?:ن|ند)?(?![آ-ی])/i;
export function contractRefundDirection(input) {
  if (!readContractRefund(input)) return null;
  const text = normalizePersian(input);
  if (REFUND_BY_US.test(text)) return 'out';
  if (TO_US.test(text)) return 'in';
  return CUSTOMER_SIDE.test(text) ? 'out' : 'in';
}
