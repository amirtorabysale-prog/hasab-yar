
/**
 * نشانهٔ پیش‌پرداخت در گفتار — ماهیت، نه دسته.
 *
 * چرا این تفکیک مهم است:
 *
 * «صد و بیست میلیون پیش‌پیش ریختیم واسه خرید ورق» دسته‌اش «مواد و کالا» است و
 * ماهیتش «پیش‌پرداخت». اگر «پیش‌پیش» را یک دسته بشماریم، هر پیش‌پرداختی در یک
 * حساب سرجمع می‌افتد و معلوم نمی‌شود بابت چه بوده. اگر هم نادیده بگیریمش —
 * کاری که تا امروز می‌شد — پول رفته‌ای که هنوز هیچ چیزی بابتش نگرفته‌ایم،
 * هزینه ثبت می‌شود.
 *
 * این تابع فقط می‌گوید «نشانه‌اش هست»؛ اینکه پیش‌پرداخت خرید است یا بیعانهٔ
 * دریافتی، از جهت حرکت پول درمی‌آید و کار موتور تصمیم است.
 */

// جداکنندهٔ میان اجزای یک عبارت: فاصله، نیم‌فاصله، یا هیچ.
//
// الگو روی **متن خام** اجرا می‌شود، نه نرمال‌شده. `normalizePersian` یک پیمایش
// کامل رشته است و تایپ زنده بودجهٔ میلی‌ثانیه‌ای دارد؛ وقتی می‌شود خودِ الگو را
// نسبت به نیم‌فاصله و «ی» عربی بردبار کرد، پرداختن آن هزینه هدر است.
const GAP = '[\\s\\u200c]*';
const YA = '[یي]';

const PREPAYMENT_WORDS = new RegExp([
  `پ${YA}ش${GAP}پرداخت`,
  `پ${YA}ش${GAP}پ${YA}ش`,
  `جلو${GAP}جلو`,
  'بیعانه',
  'بيعانه',
  `عل${YA}${GAP}الحساب`,
  `پ${YA}ش${GAP}قسط`,
  `پ${YA}شاپ${YA}ش`,
].join('|'));

export function readPrepaymentMention(input) {
  return PREPAYMENT_WORDS.test(String(input || ''));
}
